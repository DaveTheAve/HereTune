def analyze_video(
    path: Path,
    info: MediaInfo,
    ffmpeg: str,
    samples: int,
    analysis_width: int,
    strength: float,
    white_balance: bool,
    tone: bool,
    saturation_correction: bool,
    skin_priority: float,
    advanced_tone: bool = True,
    sharpening: bool = True,
    temperature_tint: bool = True,
    temperature_tint_strength: float = 0.45,
    max_sharpen: float = 3.0,
    per_channel_color: bool = True,
    per_channel_strength: float = 0.55,
    max_channel_gamma_delta: float = 0.045,
    max_channel_offset: float = 0.016,
    max_channel_contrast_delta: float = 0.035,
    max_channel_saturation_delta: float = 0.030,
    scene_grading: bool = True,
    scene_max_keyframes: int = 0,
    scene_min_seconds: float = 30.0,
    scene_change_threshold: float = 1.15,
    scene_min_confidence: float = 0.62,
    scene_probe_interval_seconds: float = 10.0,
    scene_probe_width: int = 480,
    scene_boundary_refine_seconds: float = 2.0,
    scene_probe_persistence: int = 2,
    scene_full_samples_per_segment: int = 9,
    scene_probe_max_samples: int = 900,
    ffmpeg_sample_timeout_seconds: float = 20.0,
    execution_mode: str = "auto",
    auto_preference: str = "hybrid",
    gpu_device: int = 0,
    gpu_decode_workers: int = 4,
    cpu_analysis_workers: int = 8,
    gpu_fallback_to_cpu: bool = True,
    adaptive_sampling: bool = True,
    sample_interval_seconds: float = 30.0,
    max_samples: int = 360,
    smart_sampling: bool = False,
    candidate_multiplier: float = 1.35,
    on_sample: Optional[Callable[[int, int], None]] = None,
    on_diagnostic: Optional[Callable[[dict[str, object]], None]] = None,
    worker_plan_provider: Optional[Callable[[], object]] = None,
    analysis_cache: object | None = None,
    on_stage: Optional[Callable[[str, dict[str, object]], None]] = None,
) -> CorrectionProfile:
    global _SAMPLE_TIMEOUT_SECONDS
    _SAMPLE_TIMEOUT_SECONDS = max(5.0, float(ffmpeg_sample_timeout_seconds))

    def emit_diagnostic(
        stage: str, message: str, *, timestamp: float | None = None,
        kind: str = "", severity: str = "warning", traceback_text: str = "",
    ) -> None:
        if on_diagnostic is None:
            return
        payload: dict[str, object] = {
            "stage": stage, "message": message, "kind": kind, "severity": severity,
        }
        if timestamp is not None:
            payload["timestamp"] = float(timestamp)
        if traceback_text:
            payload["traceback"] = traceback_text
        try:
            on_diagnostic(payload)
        except Exception:
            # Diagnostics are intentionally side-channel only. A broken logger
            # must never be able to fail an otherwise valid analysis.
            pass

    def emit_stage(stage: str, **details: object) -> None:
        if on_stage is None:
            return
        try:
            on_stage(stage, dict(details))
        except Exception:
            pass

    if info.width <= 0 or info.height <= 0:
        raise VideoAutoFixError("Invalid video dimensions")

    requested_samples = max(4, int(samples))
    target_samples = effective_sample_count(
        info.duration,
        requested_samples,
        adaptive_sampling=adaptive_sampling,
        sample_interval_seconds=sample_interval_seconds,
        max_samples=max_samples,
    )
    base_target_samples = target_samples
    samples = target_samples
    if smart_sampling:
        samples = min(
            max(target_samples, int(math.ceil(target_samples * max(1.0, float(candidate_multiplier))))),
            target_samples + 24,
        )
        if int(max_samples) > 0:
            samples = min(samples, int(max_samples))

    w = min(int(analysis_width), info.width)
    h = max(2, int(round(info.height * (w / info.width))))
    # Keep dimensions even for maximum swscale/CUDA compatibility.
    if w % 2:
        w -= 1
    if h % 2:
        h -= 1
    w = max(2, w)
    h = max(2, h)

    margin = min(2.0, max(0.0, info.duration * 0.04))
    start_t = margin
    end_t = max(start_t, info.duration - margin)
    if samples == 1 or end_t <= start_t + 0.001:
        timestamps = [max(0.0, info.duration * 0.5)]
    else:
        timestamps = np.linspace(start_t, end_t, samples).tolist()
    # ``timestamps`` is provisional until the dense scene pass has run. It is
    # sufficient for GPU preflight, then the dense scene pass may replace it with expensive
    # samples distributed inside the detected stable grade segments.

    # Resolve Auto once per video. Auto intentionally prefers Hybrid when the
    # installed FFmpeg can initialize the complete CUDA sampling path.
    class _ModeCfg:
        pass

    mode_cfg = _ModeCfg()
    mode_cfg.execution_mode = execution_mode
    mode_cfg.auto_preference = auto_preference
    mode_cfg.gpu_device = gpu_device
    mode_cfg.gpu_fallback_to_cpu = gpu_fallback_to_cpu
    try:
        resolved_mode, _ = resolve_execution_mode(mode_cfg, ffmpeg)
    except RuntimeError as exc:
        raise VideoAutoFixError(str(exc)) from exc

    # Before launching dozens of CUDA jobs, prove this particular file can use
    # the GPU path. This avoids 48-72 identical GPU failures on codecs/dimensions
    # that NVDEC cannot handle, while retaining per-sample fallback for occasional
    # seek-specific failures after a successful preflight.
    gpu_preflight_fallback = False
    gpu_preflight_error = ""
    gpu_strategy = "auto"
    gpu_compat_mode = False
    if resolved_mode in {"gpu", "hybrid"} and timestamps:
        # Try the full CUDA resize path first, then a compatibility path that
        # still uses NVDEC but performs the small sample resize on CPU. This
        # avoids declaring an entire video "GPU unavailable" merely because
        # scale_cuda cannot convert that file's decoder surface format.
        preflight_t = timestamps[len(timestamps) // 2]
        preflight_errors: list[str] = []
        preflight_frame = None
        for strategy in ("gpu", "gpu-decode"):
            frame, error = _sample_frame_gpu_strategy(
                path, ffmpeg, preflight_t, w, h, gpu_device, strategy
            )
            if frame is not None:
                preflight_frame = frame
                gpu_strategy = strategy
                gpu_compat_mode = strategy == "gpu-decode"
                break
            preflight_errors.append(f"{strategy}: {error}")
        if preflight_frame is None and gpu_fallback_to_cpu:
            resolved_mode = "cpu"
            gpu_preflight_fallback = True
            gpu_preflight_error = " | ".join(preflight_errors)

    stats: list[dict] = []
    sampling_errors: list[str] = []
    cpu_samples = 0
    gpu_samples = 0
    gpu_fallback_samples = 0
    gpu_compat_samples = 0
    completed = 0
    sample_timings_ms: list[float] = []
    cache_resume_samples = 0
    cache_saved_samples = 0

    def account(kind: str) -> None:
        nonlocal cpu_samples, gpu_samples, gpu_fallback_samples, gpu_compat_samples, completed
        if kind == "gpu":
            gpu_samples += 1
        elif kind == "gpu-compat":
            gpu_samples += 1
            gpu_compat_samples += 1
        elif kind == "cpu-fallback":
            cpu_samples += 1
            gpu_fallback_samples += 1
        elif kind == "cpu":
            cpu_samples += 1
        elif kind == "cache":
            pass
        completed += 1
        if on_sample:
            on_sample(completed, len(timestamps))

    prefer_gpu = resolved_mode in {"gpu", "hybrid"}
    gpu_workers = max(1, int(gpu_decode_workers))
    cpu_workers = max(1, int(cpu_analysis_workers))
    gpu_worker_peak = 1
    cpu_worker_peak = 1

    def desired_workers() -> tuple[int, int]:
        """Return current adaptive concurrency, bounded by configured ceilings."""
        nonlocal gpu_worker_peak, cpu_worker_peak
        desired_gpu, desired_cpu = gpu_workers, cpu_workers
        if worker_plan_provider is not None:
            try:
                plan = worker_plan_provider()
                if isinstance(plan, dict):
                    desired_gpu = int(plan.get("gpu_workers", desired_gpu) or desired_gpu)
                    desired_cpu = int(plan.get("cpu_workers", desired_cpu) or desired_cpu)
                else:
                    desired_gpu = int(getattr(plan, "gpu_workers", desired_gpu) or desired_gpu)
                    desired_cpu = int(getattr(plan, "cpu_workers", desired_cpu) or desired_cpu)
            except Exception:
                pass
        desired_gpu = max(1, min(gpu_workers, desired_gpu))
        desired_cpu = max(1, min(cpu_workers, desired_cpu))
        gpu_worker_peak = max(gpu_worker_peak, desired_gpu)
        cpu_worker_peak = max(cpu_worker_peak, desired_cpu)
        return desired_gpu, desired_cpu

    def sample_one(
        timestamp: float,
        use_gpu: bool,
        allow_cpu: bool,
        *,
        width: int | None = None,
        height: int | None = None,
    ):
        sample_w = int(width if width is not None else w)
        sample_h = int(height if height is not None else h)
        started = time.perf_counter()
        if use_gpu and gpu_strategy in {"gpu", "gpu-decode"}:
            frame, error = _sample_frame_gpu_strategy(
                path, ffmpeg, timestamp, sample_w, sample_h, gpu_device, gpu_strategy
            )
            elapsed_ms = (time.perf_counter() - started) * 1000.0
            if frame is not None:
                return frame, ("gpu-compat" if gpu_strategy == "gpu-decode" else "gpu"), "", elapsed_ms
            if allow_cpu:
                cpu_frame, _cpu_kind, cpu_error = _sample_frame_with_fallback(
                    path, ffmpeg, timestamp, sample_w, sample_h, False, gpu_device, False
                )
                elapsed_ms = (time.perf_counter() - started) * 1000.0
                if cpu_frame is not None:
                    return cpu_frame, "cpu-fallback", error, elapsed_ms
                return None, "cpu-fallback", f"GPU: {error} | CPU: {cpu_error}", elapsed_ms
            return None, "gpu", error, elapsed_ms
        frame, kind, error = _sample_frame_with_fallback(
            path, ffmpeg, timestamp, sample_w, sample_h, use_gpu, gpu_device, allow_cpu
        )
        return frame, kind, error, (time.perf_counter() - started) * 1000.0

    # ------------------------------------------------------------------
    # Dense low-cost scene probe pass.  The normal correction analysis stays
    # at ``analysis_width`` (960px by default).  This separate pass uses only
    # 384-480px frames and inexpensive histogram/chroma statistics so temporal
    # coverage can be roughly one probe every ten seconds without turning every
    # probe into a full face/skin/detail analysis.
    scene_probe_stats: list[dict] = []
    scene_refinement_stats: list[dict] = []
    scene_boundary_times: list[float] = []
    scene_boundary_scores: list[float] = []
    scene_boundary_confidence = 0.0
    scene_probe_interval = 0.0
    dense_scene_sampling = bool(scene_grading) and info.duration >= max(80.0, float(scene_min_seconds) * 1.5)

    probe_w = min(max(192, int(scene_probe_width)), info.width)
    probe_h = max(2, int(round(info.height * (probe_w / info.width))))
    if probe_w % 2:
        probe_w -= 1
    if probe_h % 2:
        probe_h -= 1
    probe_w = max(2, probe_w)
    probe_h = max(2, probe_h)

    def acquire_scene_probe_stats(probe_times: list[float], cache_kind: str = "probe") -> list[dict]:
        if not probe_times:
            return []
        results: list[dict] = []
        # Dense probing is seek/I/O heavy but CPU-light.  Keep CPU-only probing
        # modestly parallel and let the configured GPU acquisition ceiling apply
        # when NVDEC is active.
        if prefer_gpu:
            worker_count = max(1, min(gpu_workers, 4))
        else:
            worker_count = max(1, min(cpu_workers, 2))

        def probe_one(timestamp: float):
            nonlocal cache_resume_samples, cache_saved_samples
            started = time.perf_counter()
            if analysis_cache is not None:
                try:
                    cached = analysis_cache.get_stat(cache_kind, timestamp, probe_w)
                except Exception:
                    cached = None
                if cached is not None:
                    cached["_timestamp"] = float(timestamp)
                    cached["_source_kind"] = "cache"
                    cache_resume_samples += 1
                    return timestamp, cached, "", 0.0, ""
            try:
                frame, _kind, error, elapsed_ms = sample_one(
                    timestamp, prefer_gpu, gpu_fallback_to_cpu,
                    width=probe_w, height=probe_h,
                )
            except Exception as exc:
                detail = f"{type(exc).__name__}: {exc}"
                return timestamp, None, detail, (time.perf_counter() - started) * 1000.0, traceback.format_exc()
            if frame is None:
                return timestamp, None, error, elapsed_ms, ""
            try:
                stat = scene_probe_statistics(frame)
                stat["_timestamp"] = float(timestamp)
                stat["_source_kind"] = _kind
                if analysis_cache is not None:
                    try:
                        analysis_cache.put_stat(cache_kind, timestamp, probe_w, stat)
                        cache_saved_samples += 1
                    except Exception:
                        pass
                return timestamp, stat, "", elapsed_ms, ""
            except Exception as exc:
                detail = f"{type(exc).__name__}: {exc}"
                return timestamp, None, detail, elapsed_ms, traceback.format_exc()

        stage_name = "boundary-refinement" if cache_kind == "refine" else "scene-probe"
        total_probes = len(probe_times)
        completed_probes = 0
        if worker_count == 1:
            for timestamp in probe_times:
                _timestamp, stat, error, _elapsed, tb = probe_one(timestamp)
                completed_probes += 1
                emit_stage(stage_name, completed=completed_probes, total=total_probes, width=probe_w)
                if stat is not None:
                    results.append(stat)
                elif error:
                    emit_diagnostic("scene-probe", error, timestamp=_timestamp, kind="probe", traceback_text=tb)
            return results

        with ThreadPoolExecutor(max_workers=worker_count, thread_name_prefix="heretune-scene") as pool:
            futures = {pool.submit(probe_one, timestamp): timestamp for timestamp in probe_times}
            for future in as_completed(futures):
                timestamp = futures[future]
                completed_probes += 1
                emit_stage(stage_name, completed=completed_probes, total=total_probes, width=probe_w)
                try:
                    _timestamp, stat, error, _elapsed, tb = future.result()
                except Exception as exc:
                    emit_diagnostic(
                        "scene-probe", f"{type(exc).__name__}: {exc}",
                        timestamp=timestamp, kind="probe-future", traceback_text=traceback.format_exc(),
                    )
                    continue
                if stat is not None:
                    results.append(stat)
                elif error:
                    emit_diagnostic("scene-probe", error, timestamp=_timestamp, kind="probe", traceback_text=tb)
        return sorted(results, key=lambda item: float(item.get("_timestamp") or 0.0))

    if dense_scene_sampling:
        emit_stage("scene-probe", width=probe_w)
        probe_times, scene_probe_interval = scene_probe_timestamps(
            info.duration,
            configured_interval=float(scene_probe_interval_seconds),
            max_samples=int(scene_probe_max_samples),
        )
        scene_probe_stats = acquire_scene_probe_stats(probe_times)
        candidates, scene_boundary_confidence = detect_scene_boundaries(
            scene_probe_stats,
            info.duration,
            minimum_seconds=float(scene_min_seconds),
            change_threshold=float(scene_change_threshold),
            max_keyframes=max(0, int(scene_max_keyframes)),
            persistence=max(2, int(scene_probe_persistence)),
        )

        # Candidate boundaries are refined locally at ~2-second cadence.  This
        # gives HSP keyframes a useful timestamp without decoding the whole movie
        # every two seconds.  Neighboring refinement windows are de-duplicated.
        refine_step = max(0.75, float(scene_boundary_refine_seconds))
        refine_times: set[float] = set()
        for candidate in candidates:
            coarse = float(candidate["time_seconds"])
            radius = max(float(scene_probe_interval), refine_step * 3.0)
            lo = max(0.0, coarse - radius)
            hi = min(info.duration, coarse + radius)
            value = lo
            while value <= hi + 1e-6:
                refine_times.add(round(float(value), 6))
                value += refine_step
        if refine_times:
            emit_stage("boundary-refinement", candidates=len(candidates), step_seconds=refine_step)
            scene_refinement_stats = acquire_scene_probe_stats(sorted(refine_times), "refine")

        combined_probe_stats = sorted(
            [*scene_probe_stats, *scene_refinement_stats],
            key=lambda item: float(item.get("_timestamp") or 0.0),
        )
        for candidate in candidates:
            coarse = float(candidate["time_seconds"])
            radius = max(float(scene_probe_interval), refine_step * 3.0)
            local = [
                item for item in combined_probe_stats
                if abs(float(item.get("_timestamp") or 0.0) - coarse) <= radius * 1.25
            ]
            refined_time, refined_score = refine_scene_boundary(
                local, coarse, search_radius=radius
            )
            scene_boundary_times.append(refined_time)
            scene_boundary_scores.append(max(float(candidate.get("score") or 0.0), refined_score))

        # Refinement can move two boundaries slightly closer together.  Enforce
        # the same stable-segment spacing again before expensive analysis.
        if scene_boundary_times:
            ranked = sorted(
                zip(scene_boundary_times, scene_boundary_scores),
                key=lambda item: item[1],
                reverse=True,
            )
            stable: list[tuple[float, float]] = []
            min_gap = max(20.0, float(scene_min_seconds))
            for boundary_time, score in ranked:
                if boundary_time < min_gap or info.duration - boundary_time < min_gap * 0.65:
                    continue
                if any(abs(boundary_time - prior_time) <= min_gap for prior_time, _ in stable):
                    continue
                stable.append((boundary_time, score))
                configured_limit = max(0, int(scene_max_keyframes))
                if configured_limit > 0 and len(stable) >= max(0, configured_limit - 1):
                    break
            stable.sort(key=lambda item: item[0])
            scene_boundary_times = [item[0] for item in stable]
            scene_boundary_scores = [item[1] for item in stable]

        # Expensive 960px analysis is redistributed inside stable grade segments.
        # The configured per-segment target gives each local grade independent
        # full-resolution evidence. A positive max_samples is a hard ceiling;
        # max_samples=0 intentionally leaves the evidence budget unlimited.
        emit_stage("full-sampling", segments=len(scene_boundary_times) + 1, width=w)
        timestamps = scene_full_sample_timestamps(
            info.duration,
            scene_boundary_times,
            base_target=base_target_samples,
            per_segment=max(4, int(scene_full_samples_per_segment)),
            max_samples=int(max_samples),
        )
        samples = len(timestamps)

    # Partial resume: completed raw frame-statistics are reusable even after a
    # worker/server restart. Only timestamps absent from the checkpoint cache are
    # decoded again.
    pending_timestamps: list[float] = []
    for timestamp in timestamps:
        cached = None
        if analysis_cache is not None:
            try:
                cached = analysis_cache.get_stat("full", timestamp, w)
            except Exception:
                cached = None
        if cached is not None:
            cached["_timestamp"] = float(timestamp)
            cached["_source_kind"] = "cache"
            stats.append(cached)
            cache_resume_samples += 1
            account("cache")
        else:
            pending_timestamps.append(timestamp)
    timestamps_to_process = pending_timestamps
    emit_stage("frame-analysis", planned=len(timestamps), resumed=cache_resume_samples, remaining=len(timestamps_to_process))

    if resolved_mode == "cpu":
        for timestamp in timestamps_to_process:
            kind = "cpu"
            try:
                frame, kind, error, elapsed_ms = sample_one(timestamp, False, False)
            except Exception as exc:
                error = f"{type(exc).__name__}: {exc}"
                sample_timings_ms.append(0.0)
                sampling_errors.append(f"{timestamp:.2f}s sample: {error}")
                emit_diagnostic("full-sample", error, timestamp=timestamp, kind="cpu-sample", traceback_text=traceback.format_exc())
                account(kind)
                continue
            sample_timings_ms.append(elapsed_ms)
            account(kind)
            if frame is None:
                sampling_errors.append(f"{timestamp:.2f}s sample: {error}")
                emit_diagnostic("full-sample", error or "FFmpeg returned no frame", timestamp=timestamp, kind=kind)
                continue
            try:
                stat = _frame_statistics_thread(frame)
                stat["_timestamp"] = timestamp
                stat["_source_kind"] = kind
                stats.append(stat)
                if analysis_cache is not None:
                    try:
                        analysis_cache.put_stat("full", timestamp, w, stat)
                        cache_saved_samples += 1
                    except Exception:
                        pass
            except Exception as exc:
                error = f"{type(exc).__name__}: {exc}"
                sampling_errors.append(f"{timestamp:.2f}s statistics: {error}")
                emit_diagnostic("frame-statistics", error, timestamp=timestamp, kind=kind, traceback_text=traceback.format_exc())

    elif resolved_mode == "gpu":
        # Keep the pool at the configured ceiling but only allow the adaptive
        # planner's current number of jobs in flight. A single failed sample or
        # statistics frame is recoverable; useful evidence from the remaining
        # timestamps is still analyzed.
        frames: list[tuple[np.ndarray, str, float]] = []
        pending = deque(timestamps_to_process)
        with ThreadPoolExecutor(max_workers=gpu_workers, thread_name_prefix="heretune-gpu") as pool:
            futures: dict[object, float] = {}
            while pending or futures:
                desired_gpu, _ = desired_workers()
                while pending and len(futures) < desired_gpu:
                    timestamp = pending.popleft()
                    futures[pool.submit(sample_one, timestamp, True, gpu_fallback_to_cpu)] = timestamp
                if not futures:
                    continue
                done, _ = wait(set(futures), timeout=0.35, return_when=FIRST_COMPLETED)
                for future in done:
                    timestamp = futures.pop(future)
                    try:
                        frame, kind, error, elapsed_ms = future.result()
                    except Exception as exc:
                        kind = "gpu"
                        error = f"{type(exc).__name__}: {exc}"
                        sampling_errors.append(f"{timestamp:.2f}s sample: {error}")
                        emit_diagnostic("full-sample", error, timestamp=timestamp, kind="gpu-future", traceback_text=traceback.format_exc())
                        account(kind)
                        continue
                    sample_timings_ms.append(elapsed_ms)
                    account(kind)
                    if frame is not None:
                        frames.append((frame, kind, timestamp))
                    else:
                        sampling_errors.append(f"{timestamp:.2f}s sample: {error}")
                        emit_diagnostic("full-sample", error or "FFmpeg returned no frame", timestamp=timestamp, kind=kind)
        # GPU mode accelerates acquisition but intentionally keeps analysis on
        # the normal CPU algorithm for bit-identical correction math.
        for frame, kind, timestamp in frames:
            try:
                stat = _frame_statistics_thread(frame)
                stat["_timestamp"] = timestamp
                stat["_source_kind"] = kind
                stats.append(stat)
                if analysis_cache is not None:
                    try:
                        analysis_cache.put_stat("full", timestamp, w, stat)
                        cache_saved_samples += 1
                    except Exception:
                        pass
            except Exception as exc:
                error = f"{type(exc).__name__}: {exc}"
                sampling_errors.append(f"{timestamp:.2f}s statistics: {error}")
                emit_diagnostic("frame-statistics", error, timestamp=timestamp, kind=kind, traceback_text=traceback.format_exc())

    else:  # hybrid
        # Dynamically pipeline CUDA/NVDEC acquisition and CPU/OpenCV statistics.
        # Both stages are fault-isolated per timestamp: one malformed frame must
        # not abort the whole movie or silently poison the queue.
        pending_samples = deque(timestamps_to_process)
        pending_frames: deque[tuple[np.ndarray, float, str]] = deque()
        with ThreadPoolExecutor(max_workers=gpu_workers, thread_name_prefix="heretune-gpu") as sample_pool, \
             ThreadPoolExecutor(max_workers=cpu_workers, thread_name_prefix="heretune-cpu") as stats_pool:
            sample_futures: dict[object, float] = {}
            stats_futures: dict[object, tuple[float, str]] = {}
            while pending_samples or sample_futures or pending_frames or stats_futures:
                desired_gpu, desired_cpu = desired_workers()
                while pending_samples and len(sample_futures) < desired_gpu:
                    timestamp = pending_samples.popleft()
                    sample_futures[sample_pool.submit(
                        sample_one, timestamp, prefer_gpu, gpu_fallback_to_cpu
                    )] = timestamp
                while pending_frames and len(stats_futures) < desired_cpu:
                    frame, timestamp, kind = pending_frames.popleft()
                    stats_futures[stats_pool.submit(_frame_statistics_thread, frame)] = (timestamp, kind)

                combined = set(sample_futures) | set(stats_futures)
                if not combined:
                    continue
                done, _ = wait(combined, timeout=0.35, return_when=FIRST_COMPLETED)
                for future in done:
                    if future in sample_futures:
                        timestamp = sample_futures.pop(future)
                        try:
                            frame, kind, error, elapsed_ms = future.result()
                        except Exception as exc:
                            kind = "gpu" if prefer_gpu else "cpu"
                            error = f"{type(exc).__name__}: {exc}"
                            sampling_errors.append(f"{timestamp:.2f}s sample: {error}")
                            emit_diagnostic("full-sample", error, timestamp=timestamp, kind="sample-future", traceback_text=traceback.format_exc())
                            account(kind)
                            continue
                        sample_timings_ms.append(elapsed_ms)
                        account(kind)
                        if frame is not None:
                            pending_frames.append((frame, timestamp, kind))
                        else:
                            sampling_errors.append(f"{timestamp:.2f}s sample: {error}")
                            emit_diagnostic("full-sample", error or "FFmpeg returned no frame", timestamp=timestamp, kind=kind)
                    elif future in stats_futures:
                        timestamp, kind = stats_futures.pop(future)
                        try:
                            stat = future.result()
                            stat["_timestamp"] = timestamp
                            stat["_source_kind"] = kind
                            stats.append(stat)
                            if analysis_cache is not None:
                                try:
                                    analysis_cache.put_stat("full", timestamp, w, stat)
                                    cache_saved_samples += 1
                                except Exception:
                                    pass
                        except Exception as exc:
                            error = f"{type(exc).__name__}: {exc}"
                            sampling_errors.append(f"{timestamp:.2f}s statistics: {error}")
                            emit_diagnostic("frame-statistics", error, timestamp=timestamp, kind=kind, traceback_text=traceback.format_exc())

    rejection_counts = {"black_fade": 0, "title_like": 0, "duplicate": 0, "coverage_trim": 0}
    raw_candidate_count = len(stats)
    raw_full_stats = list(stats)
    emit_stage("sample-rejection", candidates=raw_candidate_count)
    if smart_sampling and stats:
        if dense_scene_sampling:
            # Dense scene grading still applies smart rejection within each stable segment.
            # Reject independently per stable grading segment so one scene
            # cannot consume another scene's evidence budget.
            stats, rejection_counts = _smart_select_scene_statistics(
                stats, scene_boundary_times
            )
        else:
            stats, rejection_counts = _smart_select_statistics(stats, target_samples)

    if len(stats) < 2:
        if sampling_errors:
            detail = " | ".join(sampling_errors[-5:])
        else:
            detail = "No decodable sample frames were returned."
        raise VideoAutoFixError(
            f"Not enough usable frames could be analyzed ({len(stats)}/{len(timestamps)}). {detail}"
        )

    p01 = float(np.median([s["p01"] for s in stats]))
    p05 = float(np.median([s["p05"] for s in stats]))
    p10 = float(np.median([s["p10"] for s in stats]))
    p25 = float(np.median([s["p25"] for s in stats]))
    p50 = float(np.median([s["p50"] for s in stats]))
    p75 = float(np.median([s["p75"] for s in stats]))
    p90 = float(np.median([s["p90"] for s in stats]))
    p95 = float(np.median([s["p95"] for s in stats]))
    p99 = float(np.median([s["p99"] for s in stats]))
    median_sat = float(np.median([s["median_sat"] for s in stats]))
    neutral_fraction = float(np.median([s["neutral_fraction"] for s in stats]))
    clipped_black = float(np.median([s["clipped_black_fraction"] for s in stats]))
    clipped_highlight = float(np.median([s["clipped_highlight_fraction"] for s in stats]))
    shadow_fraction = float(np.median([s["shadow_fraction"] for s in stats]))
    highlight_fraction = float(np.median([s["highlight_fraction"] for s in stats]))
    detail_score = float(np.median([s["detail_score"] for s in stats]))
    noise_score = float(np.median([s["noise_score"] for s in stats]))
    detail_log_std = float(np.std(np.log(np.clip(
        [s["detail_score"] for s in stats], 1e-7, None
    ))))
    noise_std = float(np.std([s["noise_score"] for s in stats]))
    p50_std = float(np.std([s["p50"] for s in stats]))

    profile = CorrectionProfile(
        luma_p05=p05,
        luma_p50=p50,
        luma_p95=p95,
        luma_p01=p01,
        luma_p10=p10,
        luma_p25=p25,
        luma_p75=p75,
        luma_p90=p90,
        luma_p99=p99,
        median_saturation=median_sat,
        neutral_fraction=neutral_fraction,
        clipped_black_fraction=clipped_black,
        clipped_highlight_fraction=clipped_highlight,
        shadow_fraction=shadow_fraction,
        highlight_fraction=highlight_fraction,
        sharpness_score=detail_score,
        noise_score=noise_score,
        sampled_frames=len(stats),
        requested_execution_mode=str(execution_mode),
        execution_mode=str(resolved_mode),
        cpu_samples=cpu_samples,
        gpu_samples=gpu_samples,
        gpu_fallback_samples=gpu_fallback_samples,
        gpu_preflight_fallback=gpu_preflight_fallback,
        gpu_preflight_error=gpu_preflight_error,
        gpu_compat_samples=gpu_compat_samples,
        gpu_compat_mode=gpu_compat_mode,
        sample_width=w,
        requested_samples=requested_samples,
        target_samples=target_samples,
        candidate_samples=len(timestamps),
        rejected_black_fade=int(rejection_counts.get("black_fade", 0)),
        rejected_title_like=int(rejection_counts.get("title_like", 0)),
        rejected_duplicate=int(rejection_counts.get("duplicate", 0)),
        rejected_coverage_trim=int(rejection_counts.get("coverage_trim", 0)),
        rejected_total=max(0, raw_candidate_count - len(stats)),
        cache_resume_samples=int(cache_resume_samples),
        cache_saved_samples=int(cache_saved_samples),
        average_sample_ms=float(np.mean(sample_timings_ms)) if sample_timings_ms else 0.0,
        adaptive_workers=worker_plan_provider is not None,
        gpu_worker_peak=int(gpu_worker_peak),
        cpu_worker_peak=int(cpu_worker_peak),
        scene_probe_interval_seconds=float(scene_probe_interval),
        scene_probe_width=int(probe_w if dense_scene_sampling else 0),
        scene_probe_samples=len(scene_probe_stats),
        scene_probe_refinement_samples=len(scene_refinement_stats),
        scene_full_samples=len(stats),
    )

    def inspector_item(item: dict, *, kind: str = "full") -> dict[str, object]:
        timestamp = float(item.get("_timestamp") or 0.0)
        reason = str(item.get("_rejection_reason") or "")
        return {
            "time_seconds": timestamp,
            "kind": kind,
            "accepted": bool(item.get("_accepted", True)),
            "rejection_reason": reason,
            "source": str(item.get("_source_kind") or ""),
            "p05": float(item.get("p05") or 0.0),
            "p50": float(item.get("p50") or 0.0),
            "p95": float(item.get("p95") or 0.0),
            "saturation": float(item.get("median_sat") or 0.0),
            "neutral_fraction": float(item.get("neutral_fraction") or 0.0),
            "black_fraction": float(item.get("black_fraction") or 0.0),
            "edge_density": float(item.get("edge_density") or 0.0),
            "face_samples": int(item.get("face_sample_count") or 0),
            "skin_samples": int(len(item.get("skin_samples") or [])) if isinstance(item.get("skin_samples"), (list, tuple)) else 0,
            "frame_url_key": f"full:{w}:{timestamp:.3f}",
        }

    profile.sample_inspector = [inspector_item(item) for item in sorted(raw_full_stats, key=lambda x: float(x.get("_timestamp") or 0.0))]
    # Compact scene-probe evidence powers the visual timeline without storing raw
    # images/arrays in SQLite. Refined boundary samples are marked separately.
    refined_times = {round(float(item.get("_timestamp") or 0.0), 3) for item in scene_refinement_stats}
    boundary_times_rounded = [float(value) for value in scene_boundary_times]
    timeline_items: list[dict[str, object]] = []
    for item in sorted([*scene_probe_stats, *scene_refinement_stats], key=lambda x: float(x.get("_timestamp") or 0.0)):
        timestamp = float(item.get("_timestamp") or 0.0)
        nearest = min((abs(timestamp - b) for b in boundary_times_rounded), default=999999.0)
        timeline_items.append({
            "time_seconds": timestamp,
            "kind": "refine" if round(timestamp, 3) in refined_times else "probe",
            "p50": float(item.get("p50") or 0.0),
            "saturation": float(item.get("median_sat") or 0.0),
            "boundary": nearest <= max(0.6, float(scene_boundary_refine_seconds) * 0.6),
            "frame_url_key": f"probe:{probe_w}:{timestamp:.3f}",
        })
    profile.scene_probe_timeline = timeline_items

    # ---- White balance: HUMAN SKIN FIRST ------------------------------
    effective_global_gains = np.ones(3, dtype=np.float64)
    means = np.vstack([s["channel_means"] for s in stats])
    frame_gains: list[np.ndarray] = []
    for m in means:
        m = np.maximum(m, 1e-4)
        target = float(np.exp(np.mean(np.log(m))))
        gains = target / m
        frame_gains.append(normalize_luma_gain(gains))

    gains_arr = np.vstack(frame_gains)
    neutral_raw_gains = normalize_luma_gain(np.median(gains_arr, axis=0))

    neutral_conf = clamp(neutral_fraction / 0.08, 0.0, 1.0)
    log_gain_std = float(np.mean(np.std(np.log(np.clip(gains_arr, 0.5, 2.0)), axis=0)))
    consistency_conf = math.exp(-log_gain_std / 0.10)
    wb_confidence = clamp(neutral_conf * consistency_conf, 0.0, 1.0)
    profile.wb_confidence = wb_confidence

    white_points = [
        (
            float(st.get("white_temp_estimate") or 0.0),
            float(st.get("white_tint_axis") or 0.0),
            float(st.get("white_point_fit_error") or 1.0),
        )
        for st in stats
        if 1800.0 <= float(st.get("white_temp_estimate") or 0.0) <= 15_000.0
        and float(st.get("neutral_fraction") or 0.0) >= 0.001
        and float(st.get("white_point_fit_error") or 1.0) <= 0.020
    ]
    if white_points:
        temperatures = np.asarray([item[0] for item in white_points], dtype=np.float64)
        tints = np.asarray([item[1] for item in white_points], dtype=np.float64)
        fit_errors = np.asarray([item[2] for item in white_points], dtype=np.float64)
        source_temp = float(np.median(temperatures))
        source_tint = float(np.median(tints))
        temp_spread = float(np.std(np.log(np.clip(temperatures, 1800.0, 20_000.0))))
        tint_spread = float(np.std(tints))
        coverage = clamp(len(white_points) / max(len(stats) * 0.55, 1.0), 0.0, 1.0)
        temp_conf = clamp(
            (0.25 + 0.75 * coverage)
            * math.exp(-temp_spread / 0.18)
            * math.exp(-tint_spread / 0.12)
            * math.exp(-float(np.median(fit_errors)) / 0.008)
            * (0.35 + 0.65 * neutral_conf),
            0.0,
            1.0,
        )
        profile.source_white_temp = source_temp
        profile.source_white_tint = source_tint
        profile.temperature_tint_confidence = temp_conf
        profile.temperature_tint_samples = len(white_points)

    face_skin: list[np.ndarray] = []
    fallback_skin: list[np.ndarray] = []
    for st in stats:
        samples_here = st["skin_samples"]
        if not samples_here:
            continue
        if st["face_sample_count"]:
            face_skin.extend(samples_here[:st["face_sample_count"]])
        elif st["fallback_skin"]:
            fallback_skin.extend(samples_here)

    selected_skin = face_skin if face_skin else fallback_skin
    skin_arr = (
        np.vstack(selected_skin).astype(np.float64)
        if selected_skin else np.empty((0, 3), dtype=np.float64)
    )
    profile.face_sample_count = len(face_skin)
    profile.skin_sample_count = len(selected_skin)

    skin_confidence = 0.0
    if len(skin_arr):
        _, skin_cb_arr, skin_cr_arr = rgb_to_ycbcr(np.clip(skin_arr, 0.0, 1.0))
        skin_sat_arr = pixel_saturation(np.clip(skin_arr, 0.0, 1.0))
        profile.skin_cb = float(np.median(skin_cb_arr))
        profile.skin_cr = float(np.median(skin_cr_arr))
        profile.skin_saturation = float(np.median(skin_sat_arr))

        coverage = clamp(len(skin_arr) / max(len(stats) * 0.55, 1.0), 0.0, 1.0)
        chroma_spread = float(np.sqrt(np.var(skin_cb_arr) + np.var(skin_cr_arr)))
        consistency = math.exp(-chroma_spread / 0.105)
        source_quality = 1.0 if face_skin else 0.24
        skin_confidence = clamp(source_quality * (0.35 + 0.65 * coverage) * consistency, 0.0, 1.0)
    profile.skin_confidence = skin_confidence

    if white_balance:
        raw_gains = neutral_raw_gains
        if len(skin_arr) and skin_priority > 0.0:
            raw_gains = optimize_skin_aware_gains(
                neutral_raw_gains,
                wb_confidence,
                skin_arr,
                skin_confidence,
                skin_priority,
            )
            profile.wb_method = "face-skin+neutral" if face_skin else "skin-fallback+neutral"
        else:
            profile.wb_method = "neutral"

        # Confidence from EITHER trustworthy skin or neutrals can justify the
        # correction, but even maximum strength remains bounded and global.
        combined_conf = max(wb_confidence * 0.75, skin_confidence)
        wb_strength = strength * 0.94 * (0.42 + 0.58 * combined_conf)
        raw_gains = np.clip(raw_gains, 0.76, 1.32)
        final_gains = np.asarray(
            [blend_log(float(g), wb_strength) for g in raw_gains],
            dtype=np.float64,
        )
        final_gains = np.clip(final_gains, 0.80, 1.24)
        final_gains = normalize_luma_gain(final_gains)
        effective_global_gains = final_gains.copy()
        profile.r_gain, profile.g_gain, profile.b_gain = map(float, final_gains)

        # Express a conservative fraction of a trustworthy neutral correction
        # through HereSphere's native temperature/tint controls, leaving RGB
        # gain as the residual. Auto therefore gains an understandable native
        # warm/cool + green/magenta correction without abandoning the proven
        # per-channel path when evidence is weak.
        if temperature_tint and profile.temperature_tint_confidence >= 0.18:
            native_fraction = clamp(
                float(temperature_tint_strength)
                * strength
                * (0.35 + 0.65 * profile.temperature_tint_confidence),
                0.0,
                0.65,
            )
            # Interpolate in reciprocal temperature (mired space); equal Kelvin
            # steps are not perceptually or physically uniform.
            d65_mired = 1_000_000.0 / 6500.0
            source_mired = 1_000_000.0 / max(profile.source_white_temp, 1.0)
            selected_mired = d65_mired + (source_mired - d65_mired) * native_fraction
            profile.white_temp = clamp(
                1_000_000.0 / max(selected_mired, 1e-6),
                3000.0,
                10_000.0,
            )
            profile.white_tint = clamp(
                profile.source_white_tint * native_fraction,
                -0.22,
                0.22,
            )
            residual_strength = 1.0 - native_fraction * 0.82
            residual = np.asarray(
                [blend_log(float(value), residual_strength) for value in final_gains],
                dtype=np.float64,
            )
            residual = normalize_luma_gain(np.clip(residual, 0.82, 1.22))
            profile.r_gain, profile.g_gain, profile.b_gain = map(float, residual)
            profile.wb_native_mode = "hybrid-temperature-tint+rgb"
        else:
            profile.wb_native_mode = "rgb-gain"

        if len(skin_arr):
            corrected_skin = np.clip(skin_arr * final_gains[None, :], 0.0, 1.0)
            _, cb_after, cr_after = rgb_to_ycbcr(corrected_skin)
            profile.skin_cb_after = float(np.median(cb_after))
            profile.skin_cr_after = float(np.median(cr_after))

    # ---- Tone / exposure / contrast -----------------------------------
    if tone:
        # A wildly changing movie should receive a gentler one-profile grade.
        # Stable exposure evidence earns more confidence; scene intent is still
        # preserved by strict ranges and by avoiding aggressive lifting of
        # genuinely dark footage.
        tone_confidence = clamp(math.exp(-p50_std / 0.22), 0.25, 1.0)
        profile.tone_confidence = tone_confidence

        if advanced_tone:
            raw_exposure = 0.0
            if p50 < 0.19 and p95 < 0.78:
                desired_mid = 0.21 if p50 < 0.12 else 0.23
                raw_exposure = math.log2(desired_mid / max(p50, 0.035))
            elif p50 > 0.76 and p05 > 0.085:
                raw_exposure = math.log2(0.72 / max(p50, 1e-4))
            profile.exposure_bias = clamp(raw_exposure, -0.32, 0.38) * (
                strength * 0.62 * tone_confidence
            )

        exposure_scale = 2.0 ** float(profile.exposure_bias)
        ep05 = clamp(p05 * exposure_scale, 0.0, 1.0)
        ep10 = clamp(p10 * exposure_scale, 0.0, 1.0)
        ep50 = clamp(p50 * exposure_scale, 0.0, 1.0)
        ep90 = clamp(p90 * exposure_scale, 0.0, 1.0)
        ep95 = clamp(p95 * exposure_scale, 0.0, 1.0)
        ep99 = clamp(p99 * exposure_scale, 0.0, 1.0)

        span = max(ep95 - ep05, 0.08)
        # Native regional controls now shoulder part of the work, so global
        # Contrast is intentionally conservative relative to the primary tone solve.
        raw_contrast = clamp(0.84 / span, 0.92, 1.11)
        profile.contrast = 1.0 + (raw_contrast - 1.0) * (
            strength * 0.44 * tone_confidence
        )

        # Global Offset used to pull the tonal midpoint toward 0.50 before
        # Gamma and Midtones were solved. Headset A/B testing showed that this
        # additive black-floor lift was the primary haze/washed-out culprit.
        # Auto therefore treats Global Offset as if the control does not exist:
        # it is never estimated, and Gamma/Midtones are solved from exposure +
        # contrast only. This preserves the rest of the established tone stack.
        profile.brightness = 0.0
        corrected_mid, profile.gamma, offset_free_midtones = _offset_free_gamma_midtones(
            ep50, profile.contrast, strength, tone_confidence
        )

        if advanced_tone:
            # HereSphere's neutral values are Shadows=0, Midtones=1,
            # Highlights=1. The exact UI transfer curves are player-owned, so
            # the analyzer intentionally stays in a narrow, reversible band.
            dark_scene_guard = clamp((ep50 - 0.10) / 0.24, 0.0, 1.0)
            crushed = clamp((0.040 - ep05) / 0.040, 0.0, 1.0)
            lifted = clamp((ep10 - 0.14) / 0.12, 0.0, 1.0)
            shadow_target = 0.085 * crushed * dark_scene_guard - 0.045 * lifted
            profile.shadows = clamp(
                shadow_target * strength * tone_confidence, -0.08, 0.10
            )

            profile.midtones = offset_free_midtones

            clipped = max(clipped_highlight, clamp((ep99 - 0.985) / 0.015, 0.0, 1.0))
            weak_highlights = clamp((0.76 - ep95) / 0.20, 0.0, 1.0)
            highlight_delta = -0.065 * clipped + 0.035 * weak_highlights
            profile.highlights = 1.0 + clamp(
                highlight_delta * strength * tone_confidence,
                -0.075,
                0.045,
            )

    # ---- Native sharpening ---------------------------------------------
    if sharpening:
        consistency = math.exp(-detail_log_std / 1.10) * math.exp(-noise_std / 0.035)
        sharpen_confidence = clamp(0.25 + 0.75 * consistency, 0.0, 1.0)
        profile.sharpen_confidence = sharpen_confidence
        target_sharpen = 2.0
        if noise_score >= 0.045:
            target_sharpen = 1.85
        elif detail_score < 0.00018 and noise_score < 0.030:
            target_sharpen = min(float(max_sharpen), 2.85)
        elif detail_score < 0.00045 and noise_score < 0.035:
            target_sharpen = min(float(max_sharpen), 2.55)
        elif detail_score < 0.0010 and noise_score < 0.040:
            target_sharpen = min(float(max_sharpen), 2.28)
        elif detail_score > 0.0060 or noise_score > 0.038:
            target_sharpen = 1.95
        profile.sharpen = 2.0 + (target_sharpen - 2.0) * (
            strength * 0.78 * sharpen_confidence
        )

    # ---- Saturation ----------------------------------------------------
    if saturation_correction:
        # Only intervene when the footage is conspicuously flat or intense.
        raw_sat_gain = 1.0
        if median_sat < 0.10:
            raw_sat_gain = 1.10
        elif median_sat < 0.18:
            t = (0.18 - median_sat) / 0.08
            raw_sat_gain = 1.0 + 0.07 * t
        elif median_sat > 0.65:
            raw_sat_gain = 0.92
        elif median_sat > 0.50:
            t = (median_sat - 0.50) / 0.15
            raw_sat_gain = 1.0 - 0.06 * t
        # If reliable skin is already colorful, do not let a flat background
        # trick the global saturation pass into making faces orange/red.
        if profile.skin_confidence >= 0.35 and raw_sat_gain > 1.0:
            if profile.skin_saturation >= 0.48:
                raw_sat_gain = 1.0
            elif profile.skin_saturation >= 0.38:
                raw_sat_gain = min(raw_sat_gain, 1.025)
        profile.saturation = 1.0 + (raw_sat_gain - 1.0) * (strength * 0.70)

    # ---- Per-channel nonlinear finishing trims -----------------------
    if per_channel_color:
        _apply_per_channel_nonlinear_grade(
            profile,
            stats,
            effective_global_gains,
            float(per_channel_strength) * float(strength),
        )
        profile.gamma_r = clamp(
            float(profile.gamma_r), 1.0 - float(max_channel_gamma_delta),
            1.0 + float(max_channel_gamma_delta),
        )
        profile.gamma_g = clamp(
            float(profile.gamma_g), 1.0 - float(max_channel_gamma_delta),
            1.0 + float(max_channel_gamma_delta),
        )
        profile.gamma_b = clamp(
            float(profile.gamma_b), 1.0 - float(max_channel_gamma_delta),
            1.0 + float(max_channel_gamma_delta),
        )
        profile.offset_r = clamp(float(profile.offset_r), -float(max_channel_offset), float(max_channel_offset))
        profile.offset_g = clamp(float(profile.offset_g), -float(max_channel_offset), float(max_channel_offset))
        profile.offset_b = clamp(float(profile.offset_b), -float(max_channel_offset), float(max_channel_offset))
        profile.contrast_r = clamp(
            float(profile.contrast_r), 1.0 - float(max_channel_contrast_delta),
            1.0 + float(max_channel_contrast_delta),
        )
        profile.contrast_g = clamp(
            float(profile.contrast_g), 1.0 - float(max_channel_contrast_delta),
            1.0 + float(max_channel_contrast_delta),
        )
        profile.contrast_b = clamp(
            float(profile.contrast_b), 1.0 - float(max_channel_contrast_delta),
            1.0 + float(max_channel_contrast_delta),
        )
        profile.saturation_r = clamp(
            float(profile.saturation_r), 1.0 - float(max_channel_saturation_delta),
            1.0 + float(max_channel_saturation_delta),
        )
        profile.saturation_g = clamp(
            float(profile.saturation_g), 1.0 - float(max_channel_saturation_delta),
            1.0 + float(max_channel_saturation_delta),
        )
        profile.saturation_b = clamp(
            float(profile.saturation_b), 1.0 - float(max_channel_saturation_delta),
            1.0 + float(max_channel_saturation_delta),
        )

    # ---- Sparse scene-by-scene Image keyframes -----------------------
    _derive_scene_keyframes(
        profile,
        stats,
        info.duration,
        enabled=bool(scene_grading),
        minimum_seconds=float(scene_min_seconds),
        change_threshold=float(scene_change_threshold),
        max_keyframes=max(0, int(scene_max_keyframes)),
        scene_strength=min(0.80, max(0.0, float(strength) * 0.62)),
        min_confidence=float(scene_min_confidence),
        boundary_times=scene_boundary_times if dense_scene_sampling else None,
        boundary_scores=scene_boundary_scores if dense_scene_sampling else None,
        boundary_confidence=scene_boundary_confidence if dense_scene_sampling else None,
    )

    return profile

def _compact_process_error(text: str, max_lines: int = 6) -> str:
    """Make FFmpeg diagnostics readable while retaining the likely root-cause line."""
    lines = [line.strip() for line in (text or "").splitlines() if line.strip()]
    if not lines:
        return "No diagnostic text was returned by FFmpeg."

    keywords = (
        "nvenc", "cuda", "driver", "gpu", "device", "library", "dll",
        "cannot", "could not", "failed", "unsupported", "not support", "error",
        "minimum required", "required nvenc",
    )
    important = [line for line in lines if any(k in line.lower() for k in keywords)]
    chosen: list[str] = []
    for line in important + lines[-max_lines:]:
        if line not in chosen:
            chosen.append(line)
        if len(chosen) >= max_lines:
            break
    return " | ".join(chosen[:max_lines])


_MEAN_VOLUME_RE = re.compile(r"mean_volume:\s*(-?inf|[-+0-9.]+)\s*dB", re.I)
_MAX_VOLUME_RE = re.compile(r"max_volume:\s*(-?inf|[-+0-9.]+)\s*dB", re.I)


def _parse_db(match: re.Match[str] | None) -> float | None:
    if match is None:
        return None
    text = match.group(1).strip().lower()
    if text in {"-inf", "+inf", "inf"}:
        return None
    try:
        value = float(text)
    except ValueError:
        return None
    return value if math.isfinite(value) else None


def _audio_windows(duration: float, count: int = 3, window_seconds: float = 22.0) -> list[tuple[float, float]]:
    duration = max(0.0, float(duration))
    if duration < 2.0:
        return []
    window = min(float(window_seconds), max(4.0, duration / max(count * 2.5, 1.0)))
    if duration <= window + 0.25:
        return [(0.0, duration)]
    ratios = np.linspace(0.12, 0.82, max(1, int(count)))
    result: list[tuple[float, float]] = []
    for ratio in ratios:
        center = duration * float(ratio)
        start = clamp(center - window * 0.5, 0.0, max(0.0, duration - window))
        if not result or abs(start - result[-1][0]) > max(1.0, window * 0.4):
            result.append((start, min(window, duration - start)))
    return result


def _volume_window(
    path: Path, ffmpeg: str, start: float, length: float, timeout_seconds: float = 45.0
) -> tuple[float, float] | None:
    try:
        process = run_capture([
        ffmpeg, "-hide_banner", "-nostdin", "-nostats", "-loglevel", "info",
        "-ss", f"{max(0.0, start):.3f}", "-t", f"{max(0.5, length):.3f}",
        "-i", str(path), "-map", "0:a:0?", "-vn", "-sn", "-dn",
        "-af", "volumedetect", "-f", "null", "-",
        ], timeout=max(10.0, float(timeout_seconds)))
    except subprocess.TimeoutExpired:
        return None
    text = (process.stderr or b"").decode("utf-8", errors="replace")
    mean = _parse_db(_MEAN_VOLUME_RE.search(text))
    peak = _parse_db(_MAX_VOLUME_RE.search(text))
    if mean is None or peak is None:
        return None
    return mean, peak


def _analyze_audio_loudness(
    path: Path,
    ffmpeg: str,
    duration: float,
    *,
    target_mean_db: float,
    max_gain: float,
    timeout_seconds: float = 45.0,
) -> dict[str, float | int]:
    readings = [
        result
        for start, length in _audio_windows(duration)
        if (result := _volume_window(path, ffmpeg, start, length, timeout_seconds)) is not None
    ]
    if not readings:
        return {
            "mean_db": 0.0,
            "peak_db": 0.0,
            "confidence": 0.0,
            "windows": 0,
            "volume_multiplier": 1.0,
        }
    means = np.asarray([item[0] for item in readings], dtype=np.float64)
    peaks = np.asarray([item[1] for item in readings], dtype=np.float64)
    mean_db = float(np.median(means))
    peak_db = float(np.max(peaks))
    consistency = math.exp(-float(np.std(means)) / 4.5)
    confidence = clamp(min(1.0, len(readings) / 3.0) * (0.45 + 0.55 * consistency), 0.0, 1.0)
    desired_delta = clamp(float(target_mean_db) - mean_db, -6.0, 6.0)
    # Protect true peaks from clipping even if the representative mean is low.
    desired_delta = min(desired_delta, max(0.0, -1.0 - peak_db))
    multiplier = 10.0 ** (desired_delta / 20.0)
    multiplier = clamp(multiplier, 0.50, max(1.0, float(max_gain)))
    return {
        "mean_db": mean_db,
        "peak_db": peak_db,
        "confidence": confidence,
        "windows": len(readings),
        "volume_multiplier": multiplier,
    }


def _one_eye_filter(metadata: dict[str, object]) -> str:
    stereo = str(metadata.get("stereo") or "mono").lower()
    swapped = bool(metadata.get("isEyeSwapped", False))
    if stereo == "sbs":
        return "crop=iw/2:ih:" + ("iw/2:0" if swapped else "0:0")
    if stereo == "tb":
        return "crop=iw:ih/2:" + ("0:ih/2" if swapped else "0:0")
    return "null"


def _decode_sync_video(
    path: Path,
    ffmpeg: str,
    metadata: dict[str, object],
    start: float,
    length: float,
    fps: int = 10,
    width: int = 192,
    height: int = 108,
    timeout_seconds: float = 45.0,
) -> np.ndarray | None:
    filters = [_one_eye_filter(metadata), f"fps={fps}", f"scale={width}:{height}:force_original_aspect_ratio=increase", f"crop={width}:{height}", "format=rgb24"]
    try:
        process = run_capture([
        ffmpeg, "-hide_banner", "-nostdin", "-loglevel", "error",
        "-ss", f"{start:.3f}", "-t", f"{length:.3f}", "-i", str(path),
        "-map", "0:v:0", "-an", "-sn", "-dn", "-vf", ",".join(filters),
        "-f", "rawvideo", "-pix_fmt", "rgb24", "pipe:1",
        ], timeout=max(10.0, float(timeout_seconds)))
    except subprocess.TimeoutExpired:
        return None
    raw = process.stdout or b""
    frame_bytes = width * height * 3
    count = len(raw) // frame_bytes
    if process.returncode or count < max(20, fps * 3):
        return None
    return np.frombuffer(raw[:count * frame_bytes], dtype=np.uint8).reshape(count, height, width, 3).copy()


def _decode_sync_audio(
    path: Path,
    ffmpeg: str,
    start: float,
    length: float,
    rate: int = 8000,
    timeout_seconds: float = 45.0,
) -> np.ndarray | None:
    try:
        process = run_capture([
        ffmpeg, "-hide_banner", "-nostdin", "-loglevel", "error",
        "-ss", f"{start:.3f}", "-t", f"{length:.3f}", "-i", str(path),
        "-map", "0:a:0?", "-vn", "-sn", "-dn", "-ac", "1", "-ar", str(rate),
        "-f", "s16le", "pipe:1",
        ], timeout=max(10.0, float(timeout_seconds)))
    except subprocess.TimeoutExpired:
        return None
    raw = process.stdout or b""
    if process.returncode or len(raw) < rate * 2:
        return None
    return np.frombuffer(raw[:len(raw) - (len(raw) % 2)], dtype="<i2").astype(np.float64) / 32768.0


def _sync_window(
    path: Path,
    ffmpeg: str,
    metadata: dict[str, object],
    start: float,
    length: float = 9.0,
    fps: int = 10,
    timeout_seconds: float = 45.0,
) -> dict[str, float] | None:
    """Estimate speech A/V offset from face-mouth motion and audio energy.

    The method is intentionally confidence-gated and used as diagnostic
    evidence by default. It works best on speaking faces and quietly declines
    music, silent scenes, cuts, or frames without a stable face.
    """
    if cv2 is None:
        return None
    frames = _decode_sync_video(path, ffmpeg, metadata, start, length, fps=fps, timeout_seconds=timeout_seconds)
    audio = _decode_sync_audio(path, ffmpeg, start, length, timeout_seconds=timeout_seconds)
    if frames is None or audio is None or len(frames) < 24:
        return None

    probe_indexes = sorted(set((len(frames) // 4, len(frames) // 2, len(frames) * 3 // 4)))
    face_boxes: list[tuple[int, int, int, int]] = []
    detectors = load_face_detectors()
    for index in probe_indexes:
        faces = detect_faces(frames[index], detectors)
        if faces:
            face_boxes.append(max(faces, key=lambda box: box[2] * box[3]))
    if not face_boxes:
        return None
    x = int(np.median([box[0] for box in face_boxes]))
    y = int(np.median([box[1] for box in face_boxes]))
    w = int(np.median([box[2] for box in face_boxes]))
    h = int(np.median([box[3] for box in face_boxes]))
    if w < 16 or h < 16:
        return None
    # Mouth/jaw region with a little horizontal padding.
    x0 = max(0, x - int(w * 0.08)); x1 = min(frames.shape[2], x + w + int(w * 0.08))
    y0 = max(0, y + int(h * 0.48)); y1 = min(frames.shape[1], y + int(h * 1.02))
    if x1 - x0 < 12 or y1 - y0 < 8:
        return None

    gray = np.asarray([
        cv2.cvtColor(frame, cv2.COLOR_RGB2GRAY)[y0:y1, x0:x1]
        for frame in frames
    ], dtype=np.float32)
    motion = np.mean(np.abs(np.diff(gray, axis=0)), axis=(1, 2))
    # Remove slow camera motion and isolated cuts.
    motion = np.minimum(motion, np.quantile(motion, 0.92))
    if len(motion) < 20 or float(np.std(motion)) < 0.12:
        return None

    samples_per_frame = max(1, int(round(8000 / fps)))
    audio_energy: list[float] = []
    for index in range(len(motion)):
        lo = index * samples_per_frame
        hi = min(len(audio), lo + samples_per_frame)
        if hi <= lo:
            break
        rms = math.sqrt(float(np.mean(audio[lo:hi] ** 2)) + 1e-10)
        audio_energy.append(math.log(rms + 1e-6))
    n = min(len(motion), len(audio_energy))
    if n < 20:
        return None
    motion = motion[:n]
    energy = np.asarray(audio_energy[:n], dtype=np.float64)
    if float(np.std(energy)) < 0.12:
        return None

    def normalize(signal: np.ndarray) -> np.ndarray:
        signal = signal - np.median(signal)
        scale = float(np.std(signal))
        return signal / scale if scale > 1e-6 else signal

    motion_n = normalize(motion.astype(np.float64))
    energy_n = normalize(energy)
    kernel = np.ones(3, dtype=np.float64) / 3.0
    motion_n = np.convolve(motion_n, kernel, mode="same")
    energy_n = np.convolve(energy_n, kernel, mode="same")
    max_lag = max(2, int(round(fps * 0.60)))
    scores: list[tuple[float, int]] = []
    for lag in range(-max_lag, max_lag + 1):
        if lag < 0:
            left, right = motion_n[-lag:], energy_n[:n + lag]
        elif lag > 0:
            left, right = motion_n[:n - lag], energy_n[lag:]
        else:
            left, right = motion_n, energy_n
        if len(left) < 15:
            continue
        score = float(np.mean(left * right))
        scores.append((score, lag))
    if not scores:
        return None
    scores.sort(reverse=True)
    best, lag = scores[0]
    second = max((score for score, other_lag in scores[1:] if abs(other_lag - lag) >= 2), default=0.0)
    prominence = max(0.0, best - second)
    face_coverage = min(1.0, len(face_boxes) / 3.0)
    confidence = clamp(
        max(0.0, best - 0.12) / 0.38
        * min(1.0, prominence / 0.10)
        * (0.55 + 0.45 * face_coverage),
        0.0,
        1.0,
    )
    if best < 0.20 or confidence < 0.12:
        return None
    # Positive lag means later audio energy best matches current mouth motion;
    # the suggested correction advances audio. HSP application remains opt-in.
    suggested_offset = -float(lag) / float(fps)
    return {
        "timestamp": float(start + length * 0.5),
        "offset_seconds": clamp(suggested_offset, -0.75, 0.75),
        "confidence": confidence,
        "correlation": best,
        "prominence": prominence,
    }


def _analyze_av_sync(
    path: Path,
    ffmpeg: str,
    metadata: dict[str, object],
    duration: float,
    timeout_seconds: float = 45.0,
) -> dict[str, float | int]:
    if duration < 20.0:
        return {"offset": 0.0, "confidence": 0.0, "windows": 0, "drift": 0.0, "drift_confidence": 0.0}
    centers = [0.30] if duration < 180.0 else [0.22, 0.72]
    results: list[dict[str, float]] = []
    length = min(9.0, max(6.0, duration * 0.08))
    for ratio in centers:
        start = clamp(duration * ratio - length * 0.5, 0.0, max(0.0, duration - length))
        result = _sync_window(path, ffmpeg, metadata, start, length, timeout_seconds=timeout_seconds)
        if result is not None:
            results.append(result)
    if not results:
        return {"offset": 0.0, "confidence": 0.0, "windows": 0, "drift": 0.0, "drift_confidence": 0.0}
    weights = np.asarray([max(0.05, item["confidence"]) for item in results], dtype=np.float64)
    offsets = np.asarray([item["offset_seconds"] for item in results], dtype=np.float64)
    offset = float(np.average(offsets, weights=weights))
    stability = math.exp(-float(np.std(offsets)) / 0.12)
    confidence = clamp(float(np.average(weights)) * (0.55 + 0.45 * stability), 0.0, 1.0)
    drift = 0.0
    drift_confidence = 0.0
    if len(results) >= 2:
        first, last = results[0], results[-1]
        hours = max((last["timestamp"] - first["timestamp"]) / 3600.0, 1e-6)
        drift = clamp((last["offset_seconds"] - first["offset_seconds"]) / hours, -2.0, 2.0)
        drift_confidence = clamp(min(first["confidence"], last["confidence"]) * stability, 0.0, 1.0)
    return {
        "offset": offset,
        "confidence": confidence,
        "windows": len(results),
        "drift": drift,
        "drift_confidence": drift_confidence,
    }

