def analyze(
    path: Path, metadata: dict[str, object], ffmpeg: str, cfg,
    on_sample: Optional[Callable[[int, int], None]] = None,
    on_diagnostic: Optional[Callable[[dict[str, object]], None]] = None,
    worker_plan_provider: Optional[Callable[[], object]] = None,
    analysis_cache: object | None = None,
    on_stage: Optional[Callable[[str, dict[str, object]], None]] = None,
) -> CorrectionProfile:
    """Analyze one video and return a stable native correction profile.

    The baseline grade spans the whole movie. When sustained camera or lighting
    changes pass the scene-grading thresholds, the result also contains a small
    sparse sequence of complete Image keyframes; it never performs continuous
    frame-by-frame automatic white balance.

    HereTune deliberately does not auto-tune HDR or >8-bit sources until the
    player-specific HDR transfer behavior has been calibrated.  Quietly treating
    PQ/HLG as ordinary SDR would be a very confident way to make it worse.
    """
    if bool(metadata.get("is_hdr")) or int(metadata.get("bit_depth") or 8) > 8:
        raise AnalysisError(
            "HDR/>8-bit auto tuning is disabled until HereSphere HDR behavior is calibrated."
        )

    info = MediaInfo(
        duration=float(metadata.get("duration") or 0.0),
        width=int(metadata.get("width") or 0),
        height=int(metadata.get("height") or 0),
    )
    if info.duration <= 0:
        raise AnalysisError("Video duration is missing or invalid")

    def emit_stage(stage: str, **details: object) -> None:
        if on_stage is None:
            return
        try:
            on_stage(stage, dict(details))
        except Exception:
            # Stage telemetry is observational; it must never fail analysis.
            pass

    profile = analyze_video(
        path=Path(path),
        info=info,
        ffmpeg=ffmpeg,
        samples=int(cfg.samples),
        analysis_width=int(cfg.analysis_width),
        strength=float(cfg.strength),
        white_balance=bool(cfg.white_balance),
        tone=bool(cfg.tone),
        saturation_correction=bool(cfg.saturation),
        skin_priority=float(cfg.skin_priority),
        advanced_tone=bool(getattr(cfg, "advanced_tone", True)),
        sharpening=bool(getattr(cfg, "sharpening", True)),
        temperature_tint=bool(getattr(cfg, "temperature_tint", True)),
        temperature_tint_strength=float(getattr(cfg, "temperature_tint_strength", 0.45)),
        max_sharpen=float(getattr(cfg, "max_sharpen", 3.0)),
        per_channel_color=bool(getattr(cfg, "per_channel_color", True)),
        per_channel_strength=float(getattr(cfg, "per_channel_strength", 0.55)),
        max_channel_gamma_delta=float(getattr(cfg, "max_channel_gamma_delta", 0.045)),
        max_channel_offset=float(getattr(cfg, "max_channel_offset", 0.016)),
        max_channel_contrast_delta=float(getattr(cfg, "max_channel_contrast_delta", 0.035)),
        max_channel_saturation_delta=float(getattr(cfg, "max_channel_saturation_delta", 0.030)),
        scene_grading=bool(getattr(cfg, "scene_grading", True)),
        scene_max_keyframes=int(getattr(cfg, "scene_max_keyframes", 0)),
        scene_min_seconds=float(getattr(cfg, "scene_min_seconds", 30.0)),
        scene_change_threshold=float(getattr(cfg, "scene_change_threshold", 1.15)),
        scene_min_confidence=float(getattr(cfg, "scene_min_confidence", 0.62)),
        scene_probe_interval_seconds=float(getattr(cfg, "scene_probe_interval_seconds", 10.0)),
        scene_probe_width=int(getattr(cfg, "scene_probe_width", 480)),
        scene_boundary_refine_seconds=float(getattr(cfg, "scene_boundary_refine_seconds", 2.0)),
        scene_probe_persistence=int(getattr(cfg, "scene_probe_persistence", 2)),
        scene_full_samples_per_segment=int(getattr(cfg, "scene_full_samples_per_segment", 9)),
        scene_probe_max_samples=int(getattr(cfg, "scene_probe_max_samples", 900)),
        ffmpeg_sample_timeout_seconds=float(getattr(cfg, "ffmpeg_sample_timeout_seconds", 20.0)),
        execution_mode=str(getattr(cfg, "execution_mode", "auto")),
        auto_preference=str(getattr(cfg, "auto_preference", "hybrid")),
        gpu_device=int(getattr(cfg, "gpu_device", 0)),
        gpu_decode_workers=int(getattr(cfg, "gpu_decode_workers", 4)),
        cpu_analysis_workers=int(getattr(cfg, "cpu_analysis_workers", 8)),
        gpu_fallback_to_cpu=bool(getattr(cfg, "gpu_fallback_to_cpu", True)),
        adaptive_sampling=bool(getattr(cfg, "adaptive_sampling", True)),
        sample_interval_seconds=float(getattr(cfg, "sample_interval_seconds", 30.0)),
        max_samples=int(getattr(cfg, "max_samples", 360)),
        smart_sampling=bool(getattr(cfg, "smart_sampling", True)),
        candidate_multiplier=float(getattr(cfg, "candidate_multiplier", 1.35)),
        on_sample=on_sample,
        on_diagnostic=on_diagnostic,
        worker_plan_provider=worker_plan_provider,
        analysis_cache=analysis_cache,
        on_stage=on_stage,
    )

    # The mature analyzer already uses these defaults. Re-apply configurable
    # bounds here so a future config change cannot serialize an extreme profile.
    gains = normalize_luma_gain(np.clip(
        np.asarray([profile.r_gain, profile.g_gain, profile.b_gain], dtype=np.float64),
        float(cfg.min_rgb_gain),
        float(cfg.max_rgb_gain),
    ))
    profile.r_gain, profile.g_gain, profile.b_gain = map(float, gains)
    profile.contrast = clamp(float(profile.contrast), 0.88, 1.16)
    # Global Offset is not an Auto-analysis degree of freedom.
    profile.brightness = 0.0
    profile.gamma = clamp(float(profile.gamma), 0.88, 1.14)
    profile.saturation = clamp(float(profile.saturation), 0.88, 1.12)
    profile.sharpen = clamp(
        float(profile.sharpen), 1.75, float(getattr(cfg, "max_sharpen", 3.0))
    )
    profile.exposure_bias = clamp(float(profile.exposure_bias), -0.35, 0.40)
    profile.white_temp = clamp(float(profile.white_temp), 3000.0, 10_000.0)
    profile.white_tint = clamp(float(profile.white_tint), -0.25, 0.25)
    profile.shadows = clamp(float(profile.shadows), -0.10, 0.12)
    profile.midtones = clamp(float(profile.midtones), 0.92, 1.08)
    profile.highlights = clamp(float(profile.highlights), 0.90, 1.06)

    gamma_delta = float(getattr(cfg, "max_channel_gamma_delta", 0.045))
    contrast_delta = float(getattr(cfg, "max_channel_contrast_delta", 0.035))
    saturation_delta = float(getattr(cfg, "max_channel_saturation_delta", 0.030))
    offset_limit = float(getattr(cfg, "max_channel_offset", 0.016))
    for name in ("gamma_r", "gamma_g", "gamma_b"):
        setattr(profile, name, clamp(float(getattr(profile, name)), 1.0 - gamma_delta, 1.0 + gamma_delta))
    for name in ("contrast_r", "contrast_g", "contrast_b"):
        setattr(profile, name, clamp(float(getattr(profile, name)), 1.0 - contrast_delta, 1.0 + contrast_delta))
    for name in ("saturation_r", "saturation_g", "saturation_b"):
        setattr(profile, name, clamp(float(getattr(profile, name)), 1.0 - saturation_delta, 1.0 + saturation_delta))
    for name in ("offset_r", "offset_g", "offset_b"):
        setattr(profile, name, clamp(float(getattr(profile, name)), -offset_limit, offset_limit))

    # Representative audio analysis is separate from the image sampling loop so
    # it can fail independently without discarding a valid video grade.
    emit_stage("audio-analysis")
    has_audio = bool(metadata.get("audio_codecs"))
    if bool(getattr(cfg, "audio_correction", True)) and has_audio:
        if bool(getattr(cfg, "loudness_normalization", True)):
            try:
                loudness = _analyze_audio_loudness(
                    Path(path),
                    ffmpeg,
                    info.duration,
                    target_mean_db=float(getattr(cfg, "target_audio_mean_db", -20.0)),
                    max_gain=float(getattr(cfg, "max_audio_gain", 1.35)),
                    timeout_seconds=float(getattr(cfg, "ffmpeg_aux_timeout_seconds", 45.0)),
                )
                profile.audio_mean_db = float(loudness["mean_db"])
                profile.audio_peak_db = float(loudness["peak_db"])
                profile.audio_loudness_confidence = float(loudness["confidence"])
                profile.audio_loudness_windows = int(loudness["windows"])
                if profile.audio_loudness_confidence >= 0.30:
                    profile.audio_volume_multiplier = float(loudness["volume_multiplier"])
                    profile.audio_volume_auto_applied = abs(profile.audio_volume_multiplier - 1.0) >= 0.01
            except Exception as exc:
                emit_diagnostic(
                    "audio-loudness", f"{type(exc).__name__}: {exc}", kind="aux",
                    traceback_text=traceback.format_exc(),
                )

        if bool(getattr(cfg, "audio_sync_analysis", True)):
            try:
                sync = _analyze_av_sync(
                    Path(path), ffmpeg, metadata, info.duration,
                    timeout_seconds=float(getattr(cfg, "ffmpeg_aux_timeout_seconds", 45.0)),
                )
                profile.suggested_audio_time_offset = float(sync["offset"])
                profile.av_sync_confidence = float(sync["confidence"])
                profile.av_sync_windows = int(sync["windows"])
                profile.suggested_sync_drift_seconds_per_hour = float(sync["drift"])
                profile.sync_drift_confidence = float(sync["drift_confidence"])
                if (
                    bool(getattr(cfg, "audio_sync_auto_apply", False))
                    and profile.av_sync_confidence >= 0.68
                    and abs(profile.suggested_audio_time_offset) <= 0.50
                ):
                    profile.audio_time_offset = profile.suggested_audio_time_offset
                    if profile.sync_drift_confidence >= 0.72:
                        profile.sync_drift_seconds_per_hour = profile.suggested_sync_drift_seconds_per_hour
                    profile.audio_sync_auto_applied = True
            except Exception as exc:
                emit_diagnostic(
                    "audio-sync", f"{type(exc).__name__}: {exc}", kind="aux",
                    traceback_text=traceback.format_exc(),
                )

    emit_stage("native-calibration")
    # Clamp every sparse scene mapping independently. The first keyframe is
    # always time zero, and a disabled/low-confidence scene detector still
    # carries one full baseline keyframe for deterministic HSP rebuilds.
    cleaned_scenes: list[dict[str, object]] = []
    for item in profile.scene_keyframes:
        if not isinstance(item, dict) or not isinstance(item.get("native"), dict):
            continue
        native = dict(item["native"])
        gain = normalize_luma_gain(np.clip(
            np.asarray(tuple(native.get("gain", (1.0, 1.0, 1.0, 1.0)))[:3], dtype=np.float64),
            float(cfg.min_rgb_gain),
            float(cfg.max_rgb_gain),
        ))
        native["gain"] = (*map(float, gain), 1.0)

        def vec4(name: str, rgb_neutral: float, global_value: float, rgb_delta: float, global_lo: float, global_hi: float):
            raw = tuple(native.get(name, (rgb_neutral, rgb_neutral, rgb_neutral, global_value)))
            if len(raw) != 4:
                raw = (rgb_neutral, rgb_neutral, rgb_neutral, global_value)
            return (
                clamp(float(raw[0]), rgb_neutral - rgb_delta, rgb_neutral + rgb_delta),
                clamp(float(raw[1]), rgb_neutral - rgb_delta, rgb_neutral + rgb_delta),
                clamp(float(raw[2]), rgb_neutral - rgb_delta, rgb_neutral + rgb_delta),
                clamp(float(raw[3]), global_lo, global_hi),
            )

        native["saturation"] = vec4("saturation", 1.0, profile.saturation, saturation_delta, 0.88, 1.12)
        native["contrast"] = vec4("contrast", 1.0, profile.contrast, contrast_delta, 0.88, 1.16)
        native["gamma"] = vec4("gamma", 1.0, profile.gamma, gamma_delta, 0.88, 1.14)
        raw_offset = tuple(native.get("offset", (0.0, 0.0, 0.0, 0.0)))
        if len(raw_offset) != 4:
            raw_offset = (0.0, 0.0, 0.0, 0.0)
        native["offset"] = (
            clamp(float(raw_offset[0]), -offset_limit, offset_limit),
            clamp(float(raw_offset[1]), -offset_limit, offset_limit),
            clamp(float(raw_offset[2]), -offset_limit, offset_limit),
            0.0,
        )
        native["sharpen"] = clamp(float(native.get("sharpen", 2.0)), 1.75, float(getattr(cfg, "max_sharpen", 3.0)))
        native["exposure_bias"] = clamp(float(native.get("exposure_bias", 0.0)), -0.35, 0.40)
        native["white_temp"] = clamp(float(native.get("white_temp", 6500.0)), 3000.0, 10_000.0)
        native["white_tint"] = clamp(float(native.get("white_tint", 0.0)), -0.25, 0.25)
        native["shadows"] = clamp(float(native.get("shadows", 0.0)), -0.10, 0.12)
        native["midtones"] = clamp(float(native.get("midtones", 1.0)), 0.92, 1.08)
        native["highlights"] = clamp(float(native.get("highlights", 1.0)), 0.90, 1.06)
        cleaned = dict(item)
        cleaned["native"] = native
        cleaned_scenes.append(cleaned)
    profile.scene_keyframes = sorted(cleaned_scenes, key=lambda item: float(item.get("time_seconds") or 0.0))
    if not profile.scene_keyframes:
        profile.scene_keyframes = [_profile_keyframe_dict(profile, 0.0, confidence=profile.tone_confidence, sample_count=profile.sampled_frames)]
    profile.scene_keyframes[0]["time_seconds"] = 0.0
    profile.scene_grade_boundaries = max(0, len(profile.scene_keyframes) - 1)
    coverage_conf = clamp(float(profile.sampled_frames) / max(1.0, float(profile.target_samples)), 0.0, 1.0)
    quality_conf = clamp(1.0 - float(profile.rejected_total) / max(1.0, float(profile.candidate_samples)), 0.0, 1.0)
    profile.confidence_breakdown = {
        "white_balance": float(profile.wb_confidence),
        "neutral_evidence": clamp(float(profile.neutral_fraction) / 0.08, 0.0, 1.0),
        "skin_evidence": float(profile.skin_confidence),
        "temporal_coverage": coverage_conf,
        "sample_quality": quality_conf,
        "tone_stability": float(profile.tone_confidence),
        "scene_stability": (float(profile.scene_grade_confidence) if profile.scene_grade_boundaries > 0 else None),
    }
    profile.analysis_version = ANALYSIS_VERSION
    if analysis_cache is not None:
        try:
            analysis_cache.flush()
        except Exception:
            pass
    emit_stage("complete", used=profile.sampled_frames, rejected=profile.rejected_total)
    return profile
