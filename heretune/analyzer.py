def _opencv_api_ok(module: object) -> bool:
    """Return True only for a real OpenCV cv2 module with the APIs we use."""
    required = (
        "CascadeClassifier",
        "cvtColor",
        "resize",
        "equalizeHist",
        "flip",
        "COLOR_RGB2GRAY",
        "CASCADE_SCALE_IMAGE",
        "data",
    )
    return all(hasattr(module, name) for name in required)

def _opencv_origin(module: object) -> str:
    return str(getattr(module, "__file__", None) or getattr(module, "__path__", None) or "unknown")

def _load_opencv() -> tuple[object | None, str | None]:
    """
    Import OpenCV defensively.

    A surprisingly common failure is a local file/folder named ``cv2`` shadowing
    the real OpenCV package. In that situation ``import cv2`` succeeds, but the
    imported object has no CascadeClassifier/cvtColor/etc. We retry with the
    script directory and current working directory removed from sys.path.

    If OpenCV is genuinely unavailable/broken, video processing still works via
    the NumPy whole-frame skin detector; only face-localized skin sampling is
    disabled. This is intentionally a graceful degradation instead of making
    every video fail.
    """
    first_problem: str | None = None
    try:
        candidate = importlib.import_module("cv2")
        if _opencv_api_ok(candidate):
            return candidate, None
        first_problem = (
            f"Imported cv2 from {_opencv_origin(candidate)}, but it is not a full OpenCV build "
            f"(version={getattr(candidate, '__version__', 'unknown')})."
        )
    except Exception as exc:
        first_problem = f"Initial OpenCV import failed: {exc}"

    # Retry without local import locations. This automatically recovers from a
    # cv2.py file or cv2/ directory sitting beside video_autofix.py.
    old_path = list(sys.path)
    saved_modules = {
        name: module for name, module in list(sys.modules.items())
        if name == "cv2" or name.startswith("cv2.")
    }
    for name in saved_modules:
        sys.modules.pop(name, None)

    script_dir = Path(__file__).resolve().parent
    cwd = Path.cwd().resolve()

    def keep_path(entry: str) -> bool:
        try:
            resolved = Path(entry or os.getcwd()).resolve()
        except Exception:
            return True
        return resolved not in {script_dir, cwd}

    try:
        sys.path = [entry for entry in old_path if keep_path(entry)]
        importlib.invalidate_caches()
        candidate = importlib.import_module("cv2")
        if _opencv_api_ok(candidate):
            return candidate, (
                "Recovered OpenCV after ignoring a local cv2 module/folder that was shadowing it. "
                f"Using {_opencv_origin(candidate)}."
            )
        second_problem = (
            f"Retry imported cv2 from {_opencv_origin(candidate)}, but required OpenCV APIs are still missing "
            f"(version={getattr(candidate, '__version__', 'unknown')})."
        )
    except Exception as exc:
        second_problem = f"OpenCV retry failed: {exc}"
    finally:
        sys.path = old_path

    # Do not leave a broken half-imported cv2 module behind. Restoring the
    # original module is useful for diagnostics, but this script will not call it.
    for name in list(sys.modules):
        if name == "cv2" or name.startswith("cv2."):
            sys.modules.pop(name, None)
    sys.modules.update(saved_modules)

    return None, (
        f"{first_problem} {second_problem} Face-localized skin detection is disabled; "
        "whole-frame skin analysis will be used instead. Run --doctor for details. "
        "To repair the environment, remove conflicting OpenCV packages and reinstall "
        "opencv-python-headless."
    )

def clamp(value: float, lo: float, hi: float) -> float:
    return max(lo, min(hi, value))


def _offset_free_gamma_midtones(
    ep50: float,
    contrast: float,
    strength: float,
    tone_confidence: float,
) -> tuple[float, float, float]:
    """Solve midpoint-dependent controls without a Global Offset term.

    Headset A/B testing identified additive whole-image Offset as the primary
    haze/washed-out culprit. Gamma and Midtones therefore derive from the
    exposure-adjusted midpoint and contrast only; Global Offset is not estimated
    first and cannot influence either result. Formulas otherwise preserve the
    the established offset-free tone behavior.
    """
    corrected_mid = clamp(0.18 + float(contrast) * (float(ep50) - 0.18), 0.01, 0.99)
    raw_gamma = 1.0
    if corrected_mid < 0.20:
        raw_gamma = math.log(corrected_mid) / math.log(0.22)
    elif corrected_mid > 0.80:
        raw_gamma = math.log(corrected_mid) / math.log(0.76)
    raw_gamma = clamp(raw_gamma, 0.93, 1.08)
    gamma = 1.0 + (raw_gamma - 1.0) * (float(strength) * 0.42 * float(tone_confidence))
    mid_error = clamp((0.39 - corrected_mid) / 0.20, -1.0, 1.0)
    midtones = 1.0 + clamp(
        mid_error * 0.055 * float(strength) * float(tone_confidence),
        -0.055,
        0.065,
    )
    return corrected_mid, gamma, midtones

def blend_log(value: float, strength: float) -> float:
    """Blend multiplicative values toward 1.0 in log space."""
    value = max(value, 1e-6)
    return math.exp(math.log(value) * strength)

def rgb_to_ycbcr(rgb: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return full-range normalized Y, Cb, Cr for RGB values in [0, 1]."""
    r = rgb[..., 0]
    g = rgb[..., 1]
    b = rgb[..., 2]
    y = 0.2990 * r + 0.5870 * g + 0.1140 * b
    cb = 0.5 + 0.564334 * (b - y)
    cr = 0.5 + 0.713267 * (r - y)
    return y, cb, cr

def pixel_saturation(rgb: np.ndarray) -> np.ndarray:
    mx = rgb.max(axis=-1)
    mn = rgb.min(axis=-1)
    return (mx - mn) / np.maximum(mx, 0.05)


def estimate_white_point(rgb: np.ndarray) -> tuple[float, float, float] | None:
    """Fit neutral RGB evidence to HereSphere/Unreal Temp + Tint controls.

    Returns temperature, tint and a CIE-uv fit residual. The residual matters:
    colored walls or skin can be low-chroma enough to resemble a neutral sample
    while still not being explainable by a simple illuminant correction.
    """
    return estimate_unreal_temp_tint(np.asarray(rgb, dtype=np.float64))


def detail_metrics(luma: np.ndarray) -> tuple[float, float]:
    """Return scale-stable edge/detail energy and a robust noise estimate."""
    gray = np.asarray(luma, dtype=np.float32)
    if gray.ndim != 2 or min(gray.shape) < 8:
        return 0.0, 0.0
    # Avoid scene borders and letterboxing dominating the result.
    h, w = gray.shape
    crop = gray[max(1, h // 20):max(2, h - h // 20), max(1, w // 20):max(2, w - w // 20)]
    if crop.size < 64:
        crop = gray
    up = np.roll(crop, 1, axis=0)
    down = np.roll(crop, -1, axis=0)
    left = np.roll(crop, 1, axis=1)
    right = np.roll(crop, -1, axis=1)
    laplacian = up + down + left + right - 4.0 * crop
    detail = float(np.mean(laplacian * laplacian))

    local_mean = (crop + up + down + left + right) / 5.0
    residual = crop - local_mean
    median = float(np.median(residual))
    noise = float(np.median(np.abs(residual - median)) / 0.6745)
    return detail, noise

def load_face_detectors() -> list[tuple[str, object]]:
    """Load one OpenCV detector set per analysis thread.

    Hybrid mode deliberately overlaps CUDA frame acquisition with CPU/OpenCV
    analysis. ``CascadeClassifier`` instances are therefore kept thread-local
    instead of sharing one mutable detector object across worker threads.
    """
    cached = getattr(_FACE_DETECTOR_TLS, "detectors", None)
    if cached is not None:
        return cached
    if cv2 is None:
        _FACE_DETECTOR_TLS.detectors = []
        return _FACE_DETECTOR_TLS.detectors

    detectors: list[tuple[str, object]] = []
    cascade_dir = Path(cv2.data.haarcascades)
    for name, filename in (
        ("frontal", "haarcascade_frontalface_alt2.xml"),
        ("frontal_default", "haarcascade_frontalface_default.xml"),
        ("profile", "haarcascade_profileface.xml"),
    ):
        detector = cv2.CascadeClassifier(str(cascade_dir / filename))
        if not detector.empty():
            detectors.append((name, detector))
    _FACE_DETECTOR_TLS.detectors = detectors
    return detectors

def box_iou(a: tuple[int, int, int, int], b: tuple[int, int, int, int]) -> float:
    ax, ay, aw, ah = a
    bx, by, bw, bh = b
    x1, y1 = max(ax, bx), max(ay, by)
    x2, y2 = min(ax + aw, bx + bw), min(ay + ah, by + bh)
    iw, ih = max(0, x2 - x1), max(0, y2 - y1)
    inter = iw * ih
    if inter <= 0:
        return 0.0
    union = aw * ah + bw * bh - inter
    return inter / max(union, 1)

def detect_faces(
    frame_rgb: np.ndarray,
    detectors: list[tuple[str, object]],
) -> list[tuple[int, int, int, int]]:
    """
    Detect faces in a normal frame or, for very wide stereoscopic/VR frames,
    in each eye separately. Detecting each eye separately keeps faces large
    enough for the inexpensive Haar detector to find reliably.
    """
    if cv2 is None or not detectors:
        return []

    h, w = frame_rgb.shape[:2]
    gray_full = cv2.cvtColor(frame_rgb, cv2.COLOR_RGB2GRAY)

    # Always try the full frame, then add likely per-eye views. This supports
    # common side-by-side VR and square/top-bottom stereoscopic layouts without
    # changing the actual correction: both eyes always receive one global WB.
    aspect = w / max(h, 1)
    regions = [(0, 0, w, h)]
    if aspect >= 1.90:
        regions.extend([(0, 0, w // 2, h), (w // 2, 0, w - w // 2, h)])
    elif aspect <= 0.62 or 0.88 <= aspect <= 1.12:
        regions.extend([(0, 0, w, h // 2), (0, h // 2, w, h - h // 2)])

    boxes: list[tuple[int, int, int, int]] = []
    for ox, oy, rw, rh in regions:
        gray = gray_full[oy:oy + rh, ox:ox + rw]
        if gray.size == 0:
            continue

        # Upscale small eye views for face detection only. Color statistics
        # still come from the original analysis frame.
        detect_scale = clamp(300.0 / max(rw, 1), 1.0, 2.5)
        if detect_scale > 1.02:
            detect_gray = cv2.resize(
                gray, None, fx=detect_scale, fy=detect_scale,
                interpolation=cv2.INTER_CUBIC,
            )
        else:
            detect_gray = gray
        detect_gray = cv2.equalizeHist(detect_gray)

        min_side = max(24, int(min(detect_gray.shape[:2]) * 0.10))
        for name, detector in detectors:
            found = detector.detectMultiScale(
                detect_gray,
                scaleFactor=1.10,
                minNeighbors=4 if "frontal" in name else 5,
                flags=cv2.CASCADE_SCALE_IMAGE,
                minSize=(min_side, min_side),
            )
            for x, y, fw, fh in found:
                x = int(round(x / detect_scale)) + ox
                y = int(round(y / detect_scale)) + oy
                fw = int(round(fw / detect_scale))
                fh = int(round(fh / detect_scale))
                if fw >= 14 and fh >= 14:
                    boxes.append((x, y, fw, fh))

            # Profile cascades detect one direction. Flipping catches the other.
            if name == "profile":
                flipped = cv2.flip(detect_gray, 1)
                found_flip = detector.detectMultiScale(
                    flipped,
                    scaleFactor=1.10,
                    minNeighbors=5,
                    flags=cv2.CASCADE_SCALE_IMAGE,
                    minSize=(min_side, min_side),
                )
                dw = detect_gray.shape[1]
                for x, y, fw, fh in found_flip:
                    x = dw - (x + fw)
                    x = int(round(x / detect_scale)) + ox
                    y = int(round(y / detect_scale)) + oy
                    fw = int(round(fw / detect_scale))
                    fh = int(round(fh / detect_scale))
                    if fw >= 14 and fh >= 14:
                        boxes.append((x, y, fw, fh))

    # Deduplicate the same face found by multiple cascades/eye passes.
    boxes.sort(key=lambda b: b[2] * b[3], reverse=True)
    deduped: list[tuple[int, int, int, int]] = []
    for box in boxes:
        if all(box_iou(box, kept) < 0.35 for kept in deduped):
            deduped.append(box)
    return deduped[:12]

def extract_face_skin_samples(
    rgb: np.ndarray,
    faces: list[tuple[int, int, int, int]],
) -> list[np.ndarray]:
    """
    Sample cheeks and forehead rather than the whole face. This avoids hair,
    eyes, beard, background, and clothing as much as possible. We deliberately
    do NOT require the pixels to already have a textbook skin hue: a green or
    blue camera cast is exactly what we are trying to diagnose.
    """
    h, w = rgb.shape[:2]
    samples: list[np.ndarray] = []

    for x, y, fw, fh in faces:
        regions = (
            (0.16, 0.40, 0.44, 0.64),  # left upper cheek
            (0.56, 0.40, 0.84, 0.64),  # right upper cheek
            (0.30, 0.17, 0.70, 0.35),  # central forehead
        )
        chunks: list[np.ndarray] = []
        for x1f, y1f, x2f, y2f in regions:
            x1 = max(0, min(w, x + int(round(fw * x1f))))
            y1 = max(0, min(h, y + int(round(fh * y1f))))
            x2 = max(0, min(w, x + int(round(fw * x2f))))
            y2 = max(0, min(h, y + int(round(fh * y2f))))
            if x2 <= x1 or y2 <= y1:
                continue
            pixels = rgb[y1:y2, x1:x2].reshape(-1, 3)
            if not len(pixels):
                continue
            yv, _, _ = rgb_to_ycbcr(pixels)
            sat = pixel_saturation(pixels)
            good = (
                (yv > 0.045) & (yv < 0.955) &
                (sat < 0.78) &
                (pixels.max(axis=1) > 0.065)
            )
            if int(good.sum()) >= 12:
                chunks.append(pixels[good])

        if chunks:
            pixels = np.concatenate(chunks, axis=0)
            if len(pixels) >= 32:
                # Median is robust to eyes, eyebrows, lip pixels, compression
                # blocks, and the occasional bad face box.
                samples.append(np.median(pixels, axis=0).astype(np.float64))

    return samples

def extract_global_skin_sample(rgb: np.ndarray) -> Optional[np.ndarray]:
    """
    Fallback only. Broad chroma limits find plausible skin when no face was
    detected. Confidence is intentionally much lower because wood/walls can
    share similar chroma.
    """
    y, cb, cr = rgb_to_ycbcr(rgb)
    sat = pixel_saturation(rgb)
    mask = (
        (y > 0.055) & (y < 0.94) &
        (sat > 0.035) & (sat < 0.82) &
        (cb > 0.265) & (cb < 0.555) &
        (cr > 0.485) & (cr < 0.755)
    )
    count = int(mask.sum())
    min_count = max(96, int(rgb.shape[0] * rgb.shape[1] * 0.006))
    if count < min_count:
        return None
    return np.median(rgb[mask], axis=0).astype(np.float64)

def frame_statistics(
    frame_u8: np.ndarray,
    face_detectors: list[tuple[str, object]],
) -> dict:
    rgb = frame_u8.astype(np.float32) / 255.0
    r = rgb[..., 0]
    g = rgb[..., 1]
    b = rgb[..., 2]

    # Rec.709 luma coefficients are a practical approximation for analysis.
    luma = 0.2126 * r + 0.7152 * g + 0.0722 * b
    sat = pixel_saturation(rgb)

    p01, p05, p10, p25, p50, p75, p90, p95, p99 = np.quantile(
        luma, [0.01, 0.05, 0.10, 0.25, 0.50, 0.75, 0.90, 0.95, 0.99]
    )

    # Neutral references remain useful, but in v2 they are secondary to skin
    # whenever reliable human samples are available.
    midtone = (luma > 0.10) & (luma < 0.90)
    # Only genuinely low-chroma pixels count toward neutral-confidence. A
    # fallback may still provide a weak gray-world hint, but a frame full of
    # skin/wood must NOT be mistaken for a frame full of neutral references.
    strict_neutral = midtone & (sat < 0.18)
    strict_neutral_count = int(strict_neutral.sum())
    neutral = strict_neutral
    neutral_count = strict_neutral_count
    usable_count = int(midtone.sum())
    neutral_fallback_used = False

    if neutral_count < max(128, int(rgb.shape[0] * rgb.shape[1] * 0.004)) and usable_count:
        usable_sat = sat[midtone]
        cutoff = float(np.quantile(usable_sat, 0.20))
        neutral = midtone & (sat <= cutoff)
        neutral_count = int(neutral.sum())
        neutral_fallback_used = True

    if neutral_count:
        channel_means = rgb[neutral].mean(axis=0)
    else:
        channel_means = rgb.reshape(-1, 3).mean(axis=0)
    white_point = estimate_white_point(channel_means)

    # Luminance-binned neutral samples let the final grade distinguish a cast
    # confined to shadows, midtones, or highlights.  These are intentionally
    # stricter than the global fallback: if a region lacks trustworthy neutral
    # pixels it contributes no nonlinear per-channel correction.
    region_neutral: dict[str, tuple[np.ndarray | None, int]] = {}
    for region_name, lo, hi in (
        ("shadow", 0.035, 0.22),
        ("midtone", 0.22, 0.68),
        ("highlight", 0.68, 0.965),
    ):
        mask = (luma >= lo) & (luma < hi) & (sat < 0.16)
        count = int(mask.sum())
        minimum = max(48, int(rgb.shape[0] * rgb.shape[1] * 0.0015))
        region_neutral[region_name] = (
            np.asarray(rgb[mask].mean(axis=0), dtype=np.float64) if count >= minimum else None,
            count,
        )

    faces = detect_faces(frame_u8, face_detectors)
    face_skin_samples = extract_face_skin_samples(rgb, faces)
    fallback_skin = None if face_skin_samples else extract_global_skin_sample(rgb)
    skin_samples = face_skin_samples[:]
    if fallback_skin is not None:
        skin_samples.append(fallback_skin)

    neutral_fraction = strict_neutral_count / float(rgb.shape[0] * rgb.shape[1])
    median_sat = float(np.median(sat[midtone])) if usable_count else float(np.median(sat))
    detail_score, noise_score = detail_metrics(luma)

    return {
        "p01": float(p01),
        "p05": float(p05),
        "p10": float(p10),
        "p25": float(p25),
        "p50": float(p50),
        "p75": float(p75),
        "p90": float(p90),
        "p95": float(p95),
        "p99": float(p99),
        "median_sat": median_sat,
        "neutral_fraction": neutral_fraction,
        "channel_means": np.asarray(channel_means, dtype=np.float64),
        "shadow_channel_means": region_neutral["shadow"][0],
        "midtone_channel_means": region_neutral["midtone"][0],
        "highlight_channel_means": region_neutral["highlight"][0],
        "shadow_neutral_count": region_neutral["shadow"][1],
        "midtone_neutral_count": region_neutral["midtone"][1],
        "highlight_neutral_count": region_neutral["highlight"][1],
        "skin_samples": skin_samples,
        "face_sample_count": len(face_skin_samples),
        "fallback_skin": fallback_skin is not None,
        "neutral_fallback_used": neutral_fallback_used,
        "white_temp_estimate": float(white_point[0]) if white_point else 0.0,
        "white_tint_axis": float(white_point[1]) if white_point else 0.0,
        "white_point_fit_error": float(white_point[2]) if white_point else 1.0,
        "black_fraction": float(np.mean(luma < 0.035)),
        "clipped_black_fraction": float(np.mean(luma <= 0.008)),
        "clipped_highlight_fraction": float(np.mean(luma >= 0.992)),
        "shadow_fraction": float(np.mean(luma < 0.12)),
        "highlight_fraction": float(np.mean(luma > 0.88)),
        "luma_spread": float(p95 - p05),
        "edge_density": float(np.mean((np.abs(np.diff(luma, axis=0, prepend=luma[:1])) + np.abs(np.diff(luma, axis=1, prepend=luma[:, :1]))) > 0.08)),
        "detail_score": detail_score,
        "noise_score": noise_score,
        "signature": np.asarray(luma[::max(1, luma.shape[0] // 16), ::max(1, luma.shape[1] // 16)][:16, :16], dtype=np.float32).ravel(),
    }

def _smart_select_statistics(stats: list[dict], target: int) -> tuple[list[dict], dict[str, int]]:
    """Reject bad representative frames without scene clustering.

    The goal is simple: skip fades/black frames, credit/title-card-like frames,
    and near-duplicates, then keep a chronologically distributed set. This is
    intentionally *not* scene clustering or dynamic grading.
    """
    target = max(2, int(target))
    accepted: list[dict] = []
    rejected = {"black_fade": 0, "title_like": 0, "duplicate": 0, "coverage_trim": 0}
    for item in sorted(stats, key=lambda x: float(x.get("_timestamp", 0.0))):
        p50 = float(item.get("p50") or 0.0)
        p95 = float(item.get("p95") or 0.0)
        spread = float(item.get("luma_spread") or 0.0)
        black = float(item.get("black_fraction") or 0.0)
        sat = float(item.get("median_sat") or 0.0)
        edge = float(item.get("edge_density") or 0.0)
        item["_accepted"] = True
        item.pop("_rejection_reason", None)
        if p95 < 0.075 or black > 0.93 or (p50 < 0.08 and spread < 0.055):
            item["_accepted"] = False
            item["_rejection_reason"] = "black_fade"
            rejected["black_fade"] += 1
            continue
        # Conservative title/credit heuristic: mostly dark + low chroma + lots
        # of high-contrast strokes. It deliberately does not reject normal dark
        # scenes unless they also look text-heavy.
        if p50 < 0.24 and black > 0.42 and sat < 0.16 and edge > 0.105:
            item["_accepted"] = False
            item["_rejection_reason"] = "title_like"
            rejected["title_like"] += 1
            continue
        signature_value = item.get("signature")
        signature = np.asarray(signature_value if signature_value is not None else [], dtype=np.float32)
        duplicate = False
        if signature.size:
            for prior in accepted[-8:]:
                other_value = prior.get("signature")
                other = np.asarray(other_value if other_value is not None else [], dtype=np.float32)
                if other.shape == signature.shape and other.size:
                    if float(np.mean(np.abs(signature - other))) < 0.018:
                        duplicate = True
                        break
        if duplicate:
            item["_accepted"] = False
            item["_rejection_reason"] = "duplicate"
            rejected["duplicate"] += 1
            continue
        accepted.append(item)

    # If aggressive rejection left too little evidence, fill from the original
    # candidates. Reliability beats ideology; the correction still needs frames.
    if len(accepted) < min(target, 4):
        accepted = sorted(stats, key=lambda x: float(x.get("_timestamp", 0.0)))
        rejected = {"black_fade": 0, "title_like": 0, "duplicate": 0, "coverage_trim": 0}
        for item in accepted:
            item["_accepted"] = True
            item.pop("_rejection_reason", None)

    if len(accepted) > target:
        indices = np.linspace(0, len(accepted) - 1, target).round().astype(int)
        keep = {int(i) for i in indices}
        original_accepted = list(accepted)
        accepted = [item for index, item in enumerate(original_accepted) if index in keep]
        for index, item in enumerate(original_accepted):
            if index not in keep:
                item["_accepted"] = False
                item["_rejection_reason"] = "coverage_trim"
                rejected["coverage_trim"] += 1
    return accepted, rejected


def _smart_select_scene_statistics(
    stats: list[dict], boundary_times: list[float]
) -> tuple[list[dict], dict[str, int]]:
    """Apply smart rejection independently inside each stable grade segment.

    Dense scene grading already chooses expensive samples *within* each detected
    grading segment.  Running the whole-movie selector globally can let a scene with
    abundant good frames starve another scene, while skipping the selector
    entirely makes the dashboard's rejection counters lie by always reporting
    zero.  Segment-local rejection preserves evidence coverage and still removes
    fades/black, title-like, and near-duplicate full-resolution samples.
    """
    if not stats:
        return [], {"black_fade": 0, "title_like": 0, "duplicate": 0, "coverage_trim": 0}

    boundaries = sorted(
        float(value) for value in boundary_times
        if math.isfinite(float(value)) and float(value) > 0.0
    )
    buckets: list[list[dict]] = [[] for _ in range(len(boundaries) + 1)]
    for item in sorted(stats, key=lambda x: float(x.get("_timestamp", 0.0))):
        timestamp = float(item.get("_timestamp", 0.0))
        segment_index = 0
        while segment_index < len(boundaries) and timestamp >= boundaries[segment_index]:
            segment_index += 1
        buckets[segment_index].append(item)

    kept: list[dict] = []
    totals = {"black_fade": 0, "title_like": 0, "duplicate": 0, "coverage_trim": 0}
    for bucket in buckets:
        if not bucket:
            continue
        # The dense scene planner has already chosen the desired number of full
        # samples.  Here the selector is a quality gate only, not another
        # down-sampling pass, so target the bucket's existing size.
        selected, rejected = _smart_select_statistics(bucket, len(bucket))
        kept.extend(selected)
        for key in totals:
            totals[key] += int(rejected.get(key, 0))

    return sorted(kept, key=lambda x: float(x.get("_timestamp", 0.0))), totals


def _region_residual_gain(
    stats: list[dict],
    means_key: str,
    count_key: str,
    global_gains: np.ndarray,
) -> tuple[np.ndarray, float, int]:
    """Return a conservative residual gray-balance vector for one luma band."""
    values: list[np.ndarray] = []
    weights: list[float] = []
    for item in stats:
        raw = item.get(means_key)
        if raw is None:
            continue
        means = np.asarray(raw, dtype=np.float64)
        if means.shape != (3,) or not np.all(np.isfinite(means)):
            continue
        corrected = np.clip(means * global_gains, 1e-4, 2.0)
        target = float(np.exp(np.mean(np.log(corrected))))
        residual = normalize_luma_gain(target / corrected)
        values.append(np.clip(residual, 0.85, 1.18))
        weights.append(max(1.0, math.sqrt(float(item.get(count_key) or 1))))
    if not values:
        return np.ones(3, dtype=np.float64), 0.0, 0
    array = np.vstack(values)
    median = normalize_luma_gain(np.median(array, axis=0))
    spread = float(np.mean(np.std(np.log(np.clip(array, 0.7, 1.4)), axis=0)))
    coverage = min(1.0, len(values) / max(3.0, len(stats) * 0.40))
    sample_weight = min(1.0, float(np.median(weights)) / 35.0)
    confidence = clamp(
        coverage * (0.45 + 0.55 * sample_weight) * math.exp(-spread / 0.055),
        0.0,
        1.0,
    )
    return median, confidence, len(values)


def _apply_per_channel_nonlinear_grade(
    profile: CorrectionProfile,
    stats: list[dict],
    global_gains: np.ndarray,
    strength: float,
) -> None:
    """Use tiny RGB nonlinear controls for luminance-dependent residual casts.

    A single RGB gain is the safest white-balance tool and remains primary. This
    pass only acts when low-chroma evidence shows a stable *different* residual
    in shadows, midtones, or highlights. Bounds are intentionally narrow.
    """
    shadow, shadow_conf, shadow_count = _region_residual_gain(
        stats, "shadow_channel_means", "shadow_neutral_count", global_gains
    )
    mid, mid_conf, mid_count = _region_residual_gain(
        stats, "midtone_channel_means", "midtone_neutral_count", global_gains
    )
    high, high_conf, high_count = _region_residual_gain(
        stats, "highlight_channel_means", "highlight_neutral_count", global_gains
    )
    confidence = clamp((shadow_conf + 1.35 * mid_conf + high_conf) / 3.35, 0.0, 1.0)
    profile.per_channel_confidence = confidence
    profile.per_channel_samples = shadow_count + mid_count + high_count
    if confidence < 0.22 or mid_count < 2:
        return

    amount = clamp(float(strength), 0.0, 2.0) * confidence

    # Additive shadow correction. Remove the weighted luma component so this is
    # a chroma correction rather than a second brightness control.
    shadow_level = clamp(float(profile.luma_p10 or 0.10), 0.045, 0.24)
    offsets = (shadow - 1.0) * shadow_level * 0.42 * amount
    offsets -= 0.2126 * offsets[0] + 0.7152 * offsets[1] + 0.0722 * offsets[2]
    offsets = np.clip(offsets, -0.012, 0.012)

    # Reciprocal gamma around the source midtone. Solve the native power curve
    # approximately for the residual gain and blend heavily toward neutral.
    x_mid = clamp(float(profile.luma_p50 or 0.42), 0.12, 0.78)
    gamma_values = np.ones(3, dtype=np.float64)
    if abs(math.log(x_mid)) > 1e-4:
        for index, residual in enumerate(mid):
            denominator = 1.0 + math.log(max(float(residual), 1e-5)) / math.log(x_mid)
            solved = 1.0 / denominator if abs(denominator) > 1e-5 else 1.0
            gamma_values[index] = 1.0 + (solved - 1.0) * 0.42 * amount
    gamma_values = np.clip(gamma_values, 0.955, 1.045)

    # Highlight residual maps cleanly to channel contrast above the 18% pivot.
    x_high = clamp(float(profile.luma_p90 or 0.82), 0.40, 0.96)
    contrast_values = np.ones(3, dtype=np.float64)
    pivot_ratio = max(x_high / 0.18, 1.01)
    for index, residual in enumerate(high):
        solved = 1.0 + math.log(max(float(residual), 1e-5)) / math.log(pivot_ratio)
        contrast_values[index] = 1.0 + (solved - 1.0) * 0.35 * amount
    contrast_values = np.clip(contrast_values, 0.965, 1.035)

    # A very small per-channel saturation trim prevents the nonlinear controls
    # from leaving a residual chroma exaggeration. It is not used as a second WB.
    chroma_log = np.log(np.clip(mid, 0.8, 1.25))
    chroma_log -= float(np.mean(chroma_log))
    saturation_values = np.clip(1.0 + chroma_log * 0.12 * amount, 0.98, 1.02)

    profile.offset_r, profile.offset_g, profile.offset_b = map(float, offsets)
    profile.gamma_r, profile.gamma_g, profile.gamma_b = map(float, gamma_values)
    profile.contrast_r, profile.contrast_g, profile.contrast_b = map(float, contrast_values)
    profile.saturation_r, profile.saturation_g, profile.saturation_b = map(float, saturation_values)


def _scene_feature(item: dict) -> np.ndarray:
    # Frame statistics keep channel_means as a NumPy vector during analysis.
    # Never use Python's boolean fallback (``array or default``) here: NumPy
    # intentionally rejects truth-testing multi-element arrays.  This path is
    # exercised by sparse scene grading on real analyses.
    raw_means = item.get("channel_means")
    if raw_means is None:
        raw_means = (1.0, 1.0, 1.0)
    means = np.asarray(raw_means, dtype=np.float64).reshape(-1)
    if means.size != 3 or not np.all(np.isfinite(means)):
        means = np.ones(3, dtype=np.float64)
    means = np.clip(means, 1e-4, 2.0)
    return np.asarray([
        math.log(max(float(item.get("p50") or 0.20), 0.02)),
        float(item.get("p05") or 0.0),
        float(item.get("p95") or 0.0),
        math.log(float(means[0] / means[1])),
        math.log(float(means[2] / means[1])),
        float(item.get("median_sat") or 0.0),
    ], dtype=np.float64)


def _profile_keyframe_dict(
    profile: CorrectionProfile,
    time_seconds: float,
    *,
    confidence: float = 0.0,
    change_score: float = 0.0,
    sample_count: int = 0,
) -> dict[str, object]:
    """Return one self-contained, JSON-safe native Image keyframe.

    Every entry carries the complete native mapping rather than inheriting fields
    from the previous scene.  That makes stored-profile rebuilds, Mild/Strong scaling, HSP serialization,
    and UI inspection deterministic.
    """
    return {
        "time_seconds": max(0.0, float(time_seconds)),
        "confidence": clamp(float(confidence), 0.0, 1.0),
        "change_score": max(0.0, float(change_score)),
        "sample_count": max(0, int(sample_count)),
        "native": profile.native_image_settings(),
    }


def _derive_scene_keyframes(
    profile: CorrectionProfile,
    stats: list[dict],
    duration: float,
    *,
    enabled: bool,
    minimum_seconds: float,
    change_threshold: float,
    max_keyframes: int,
    scene_strength: float,
    min_confidence: float,
    boundary_times: list[float] | None = None,
    boundary_scores: list[float] | None = None,
    boundary_confidence: float | None = None,
) -> None:
    """Create sparse stable Image keyframes for sustained camera/lighting changes.

    This intentionally is *not* continuous auto white balance.  A boundary must
    remain visible on both sides of a multi-sample window, survive temporal
    spacing/hysteresis, and earn enough confidence before it becomes a native HSP
    keyframe. Temporal persistence, confidence, hysteresis/non-maximum suppression,
    and minimum segment duration keep ordinary cuts from becoming twitchy
    micro-grades. A positive max_keyframes is a user-owned ceiling; 0 is unlimited.
    """
    ordered = sorted(stats, key=lambda item: float(item.get("_timestamp") or 0.0))
    if not enabled or len(ordered) < 7 or duration < max(90.0, minimum_seconds * 1.5):
        profile.scene_keyframes = [_profile_keyframe_dict(
            profile, 0.0, confidence=profile.tone_confidence, sample_count=len(ordered)
        )]
        return

    # The normal path arrives here with boundaries found by the dense, cheap
    # scene-probe pass. The direct detector remains as a fallback
    # for unit tests/direct callers and for configurations that disable probing.
    configured_keyframe_limit = max(0, int(max_keyframes))
    boundary_limit = None if configured_keyframe_limit == 0 else max(0, configured_keyframe_limit - 1)
    if boundary_limit == 0:
        profile.scene_keyframes = [_profile_keyframe_dict(
            profile, 0.0, confidence=profile.tone_confidence, sample_count=len(ordered)
        )]
        return
    precomputed_times = sorted({
        float(value) for value in (boundary_times or [])
        if float(value) > 0.0 and float(value) < float(duration)
    })
    if boundary_limit is not None:
        precomputed_times = precomputed_times[:boundary_limit]
    candidate_scores: list[tuple[float, int]] = []
    selected: list[int] = []
    selected_times: list[float] = []
    selected_score_values: list[float] = []
    window = 3 if len(ordered) >= 10 else 2
    if precomputed_times:
        supplied_scores = list(boundary_scores or [])
        for position, timestamp in enumerate(precomputed_times):
            index = next(
                (i for i, item in enumerate(ordered) if float(item.get("_timestamp") or 0.0) >= timestamp),
                len(ordered) - 1,
            )
            index = max(1, min(len(ordered) - 1, int(index)))
            score = float(supplied_scores[position]) if position < len(supplied_scores) else float(change_threshold)
            selected.append(index)
            selected_times.append(timestamp)
            selected_score_values.append(max(0.0, score))
            candidate_scores.append((max(0.0, score), index))
    else:
        features = np.vstack([_scene_feature(item) for item in ordered])
        for index in range(window, len(ordered) - window + 1):
            before = np.median(features[index - window:index], axis=0)
            after = np.median(features[index:index + window], axis=0)
            score = _scene_change_score(before, after)
            if score >= float(change_threshold):
                candidate_scores.append((score, index))

        min_gap = max(30.0, float(minimum_seconds))
        for score, index in sorted(candidate_scores, reverse=True):
            timestamp = float(ordered[index].get("_timestamp") or 0.0)
            if timestamp < min_gap or duration - timestamp < min_gap * 0.65:
                continue
            if any(abs(timestamp - float(ordered[prior].get("_timestamp") or 0.0)) <= min_gap * 1.05 for prior in selected):
                continue
            selected.append(index)
            if boundary_limit is not None and len(selected) >= boundary_limit:
                break
        selected.sort()
        selected_times = [float(ordered[index].get("_timestamp") or 0.0) for index in selected]
        selected_score_values = [
            next((score for score, candidate_index in candidate_scores if candidate_index == index), 0.0)
            for index in selected
        ]

    if not selected:
        profile.scene_keyframes = [_profile_keyframe_dict(
            profile, 0.0, confidence=profile.tone_confidence, sample_count=len(ordered)
        )]
        return

    selected_scores = selected_score_values
    if boundary_confidence is not None and precomputed_times:
        aggregate_confidence = clamp(float(boundary_confidence), 0.0, 1.0)
    else:
        aggregate_confidence = clamp(
            (float(np.mean(selected_scores)) / max(float(change_threshold) * 1.9, 1e-6))
            * min(1.0, len(ordered) / 12.0)
            * math.exp(-float(np.std(selected_scores)) / max(float(np.mean(selected_scores)), 1e-6) * 0.18),
            0.0,
            1.0,
        )
    if aggregate_confidence < float(min_confidence):
        profile.scene_keyframes = [_profile_keyframe_dict(
            profile, 0.0, confidence=aggregate_confidence, sample_count=len(ordered)
        )]
        profile.scene_grade_confidence = aggregate_confidence
        return

    boundaries = [0] + selected + [len(ordered)]
    global_means = np.median(np.vstack([np.asarray(item["channel_means"], dtype=np.float64) for item in ordered]), axis=0)
    global_means = np.clip(global_means, 1e-4, 2.0)
    keyframes: list[dict[str, object]] = []
    local_amount = clamp(float(scene_strength), 0.0, 0.85)
    for segment_index in range(len(boundaries) - 1):
        start, end = boundaries[segment_index], boundaries[segment_index + 1]
        segment = ordered[start:end]
        if not segment:
            continue
        current = CorrectionProfile()
        for field_name in (
            "r_gain", "g_gain", "b_gain", "contrast", "gamma", "saturation",
            "sharpen", "exposure_bias", "white_temp", "white_tint", "shadows", "midtones", "highlights",
            "saturation_r", "saturation_g", "saturation_b", "contrast_r", "contrast_g", "contrast_b",
            "gamma_r", "gamma_g", "gamma_b", "offset_r", "offset_g", "offset_b",
        ):
            setattr(current, field_name, getattr(profile, field_name))

        local_p50 = float(np.median([float(item.get("p50") or profile.luma_p50 or 0.3) for item in segment]))
        local_p05 = float(np.median([float(item.get("p05") or profile.luma_p05 or 0.05) for item in segment]))
        local_p95 = float(np.median([float(item.get("p95") or profile.luma_p95 or 0.9) for item in segment]))
        local_sat = float(np.median([float(item.get("median_sat") or profile.median_saturation or 0.2) for item in segment]))
        local_means = np.median(np.vstack([np.asarray(item["channel_means"], dtype=np.float64) for item in segment]), axis=0)
        local_means = np.clip(local_means, 1e-4, 2.0)

        # Pull each scene only partway toward the movie-wide exposure and color
        # baseline. This preserves deliberate day/night changes while removing
        # abrupt camera-to-camera discontinuities.
        exposure_delta = clamp(
            math.log2(max(profile.luma_p50, 0.035) / max(local_p50, 0.035)) * 0.32 * local_amount,
            -0.18,
            0.18,
        )
        current.exposure_bias = clamp(profile.exposure_bias + exposure_delta, -0.42, 0.45)
        global_span = max(profile.luma_p95 - profile.luma_p05, 0.08)
        local_span = max(local_p95 - local_p05, 0.08)
        contrast_ratio = clamp(global_span / local_span, 0.94, 1.06)
        current.contrast = profile.contrast * blend_log(contrast_ratio, 0.35 * local_amount)
        sat_ratio = clamp(max(profile.median_saturation, 0.05) / max(local_sat, 0.05), 0.94, 1.06)
        current.saturation = profile.saturation * blend_log(sat_ratio, 0.32 * local_amount)

        residual = normalize_luma_gain(global_means / local_means)
        base_gains = np.asarray([profile.r_gain, profile.g_gain, profile.b_gain], dtype=np.float64)
        local_gains = normalize_luma_gain(base_gains * np.asarray([
            blend_log(float(value), 0.30 * local_amount) for value in residual
        ]))
        local_gains = np.clip(local_gains, 0.82, 1.22)
        current.r_gain, current.g_gain, current.b_gain = map(float, normalize_luma_gain(local_gains))

        timestamp = 0.0 if segment_index == 0 else (
            selected_times[segment_index - 1]
            if segment_index - 1 < len(selected_times)
            else float(segment[0].get("_timestamp") or 0.0)
        )
        boundary_score = 0.0 if segment_index == 0 else (
            selected_score_values[segment_index - 1]
            if segment_index - 1 < len(selected_score_values)
            else 0.0
        )
        local_consistency = math.exp(-float(np.std([
            float(item.get("p50") or local_p50) for item in segment
        ])) / 0.10)
        local_confidence = clamp(
            aggregate_confidence * (0.55 + 0.45 * local_consistency)
            * min(1.0, len(segment) / max(2.0, window)),
            0.0,
            1.0,
        )
        keyframes.append(_profile_keyframe_dict(
            current,
            timestamp,
            confidence=local_confidence,
            change_score=boundary_score,
            sample_count=len(segment),
        ))

    profile.scene_keyframes = keyframes or [_profile_keyframe_dict(
        profile, 0.0, confidence=aggregate_confidence, sample_count=len(ordered)
    )]
    profile.scene_grade_boundaries = max(0, len(profile.scene_keyframes) - 1)
    profile.scene_grade_confidence = aggregate_confidence


def interval_distance(value: np.ndarray, lo: float, hi: float) -> np.ndarray:
    return np.where(value < lo, lo - value, np.where(value > hi, value - hi, 0.0))

def normalize_luma_gain(gains: np.ndarray) -> np.ndarray:
    gains = np.asarray(gains, dtype=np.float64)
    lum_gain = 0.2126 * gains[0] + 0.7152 * gains[1] + 0.0722 * gains[2]
    return gains / max(float(lum_gain), 1e-6)

def optimize_skin_aware_gains(
    neutral_gains: np.ndarray,
    neutral_confidence: float,
    skin_samples: np.ndarray,
    skin_confidence: float,
    skin_priority: float,
) -> np.ndarray:
    """
    Search for a global RGB gain triplet that keeps detected skin inside a
    broad natural-skin chroma corridor while still respecting neutral objects.

    The corridor has a dead zone: once skin looks plausible, the optimizer is
    discouraged from pushing it toward one fixed complexion. This is the key
    safeguard against making everybody the same color.
    """
    if skin_samples.size == 0 or skin_confidence <= 0.03 or skin_priority <= 0.0:
        return normalize_luma_gain(neutral_gains)

    skin_samples = np.clip(np.asarray(skin_samples, dtype=np.float64), 0.0, 1.0)
    neutral_gains = normalize_luma_gain(np.clip(neutral_gains, 0.72, 1.38))

    # Search only two independent color axes (R/G and B/G), then luma-normalize.
    axis = np.linspace(0.78, 1.26, 41)
    best_score = float("inf")
    best = neutral_gains

    neutral_weight = 0.08 + 1.45 * neutral_confidence
    skin_weight = 4.5 * skin_priority * (0.30 + 0.70 * skin_confidence)

    for rg in axis:
        for bg in axis:
            gains = normalize_luma_gain(np.array([rg, 1.0, bg], dtype=np.float64))
            corrected = np.clip(skin_samples * gains[None, :], 0.0, 1.0)
            _, cb, cr = rgb_to_ycbcr(corrected)

            # Broad, complexion-preserving "natural" corridor. Penalty is zero
            # inside the corridor and rises quickly only for camera-like casts.
            cb_out = interval_distance(cb, 0.335, 0.470) / 0.045
            cr_out = interval_distance(cr, 0.545, 0.690) / 0.055
            corridor_penalty = float(np.mean(cb_out * cb_out + cr_out * cr_out))

            # A very weak memory-color pull helps with yellow/magenta casts that
            # are still technically inside the broad corridor. It is purposely
            # weak so complexion/undertone remains driven by the source person.
            center_penalty = float(np.mean(
                ((cb - 0.415) / 0.110) ** 2 +
                ((cr - 0.605) / 0.120) ** 2
            ))

            neutral_penalty = float(np.mean(
                (np.log(np.clip(gains, 1e-6, None)) -
                 np.log(np.clip(neutral_gains, 1e-6, None))) ** 2
            )) / (0.10 ** 2)
            identity_penalty = float(np.mean(np.log(np.clip(gains, 1e-6, None)) ** 2)) / (0.18 ** 2)

            score = (
                skin_weight * (corridor_penalty + 0.22 * center_penalty) +
                neutral_weight * neutral_penalty +
                0.14 * identity_penalty
            )
            if score < best_score:
                best_score = score
                best = gains

    return normalize_luma_gain(best)


def effective_sample_count(
    duration: float,
    base_samples: int,
    adaptive_sampling: bool = True,
    sample_interval_seconds: float = 30.0,
    max_samples: int = 360,
) -> int:
    """Choose a stable whole-video sample count without punishing short clips.

    The floor is intentionally 48 in the shipped configuration for long 5.7K+
    VR material. Adaptive sampling raises that floor from duration/cadence. A
    positive max_samples caps the result; max_samples=0 explicitly means unlimited.
    """
    result = max(4, int(base_samples))
    if adaptive_sampling and duration > 0:
        interval = max(10.0, float(sample_interval_seconds))
        result = max(result, int(math.ceil(duration / interval)))
    configured_cap = int(max_samples)
    if configured_cap > 0:
        result = min(result, configured_cap)
    # Extremely short clips should not be sampled dozens of times at nearly
    # identical timestamps.
    return min(result, max(4, int(math.ceil(max(duration, 0.0) * 4.0))))


def adaptive_scene_probe_interval(duration: float, configured_seconds: float = 10.0) -> float:
    """Return the inexpensive scene-probe cadence for a movie duration.

    Sparse grading needs much denser temporal awareness than the expensive
    skin/detail analysis.  The cadence intentionally follows broad duration
    buckets rather than scaling linearly, so a long movie stays affordable
    while a 15-minute clip is not inspected only every 45 seconds.
    """
    duration = max(0.0, float(duration))
    base = max(4.0, float(configured_seconds))
    if duration < 20.0 * 60.0:
        return min(base, 8.0)
    if duration <= 60.0 * 60.0:
        return base
    if duration <= 120.0 * 60.0:
        return max(base, 15.0)
    return max(base, 20.0)


def scene_probe_timestamps(
    duration: float,
    configured_interval: float = 10.0,
    max_samples: int = 900,
) -> tuple[list[float], float]:
    """Build a dense but bounded timeline for cheap grading-state probes."""
    duration = max(0.0, float(duration))
    if duration <= 0.0:
        return [], 0.0
    interval = adaptive_scene_probe_interval(duration, configured_interval)
    cap = max(12, int(max_samples))
    # If a very long source would exceed the hard probe cap, widen the cadence
    # instead of silently sampling only the first portion of the movie.
    interval = max(interval, duration / max(cap - 1, 1))
    margin = min(2.0, max(0.0, duration * 0.01))
    start = margin
    end = max(start, duration - margin)
    if end <= start + 0.001:
        return [duration * 0.5], interval
    count = max(2, min(cap, int(math.floor((end - start) / interval)) + 1))
    values = np.linspace(start, end, count).tolist()
    return [float(value) for value in values], float(interval)


def scene_probe_statistics(frame_u8: np.ndarray) -> dict:
    """Collect only the inexpensive statistics needed for scene segmentation.

    This deliberately skips face detection, skin sampling, sharpening/noise
    analysis, and region-specific neutral solving.  At 384-480 px it is cheap
    enough to run roughly every ten seconds while the expensive grade remains
    limited to a much smaller targeted set of frames.
    """
    rgb = frame_u8.astype(np.float32) / 255.0
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    luma = 0.2126 * r + 0.7152 * g + 0.0722 * b
    sat = pixel_saturation(rgb)
    p05, p50, p95 = np.quantile(luma, [0.05, 0.50, 0.95])
    midtone = (luma > 0.08) & (luma < 0.92)
    neutral = midtone & (sat < 0.20)
    minimum = max(48, int(rgb.shape[0] * rgb.shape[1] * 0.002))
    if int(neutral.sum()) >= minimum:
        means = rgb[neutral].mean(axis=0)
    elif int(midtone.sum()) >= minimum:
        # Lowest-chroma fifth of usable pixels is a robust enough fallback for
        # *change detection*. It is never used as a final white-balance sample.
        cutoff = float(np.quantile(sat[midtone], 0.20))
        fallback = midtone & (sat <= cutoff)
        means = rgb[fallback].mean(axis=0) if int(fallback.sum()) else rgb.reshape(-1, 3).mean(axis=0)
    else:
        means = rgb.reshape(-1, 3).mean(axis=0)
    usable_sat = sat[midtone]
    median_sat = float(np.median(usable_sat)) if usable_sat.size else float(np.median(sat))
    return {
        "p05": float(p05),
        "p50": float(p50),
        "p95": float(p95),
        "median_sat": median_sat,
        "channel_means": np.asarray(means, dtype=np.float64),
        "black_fraction": float(np.mean(luma < 0.035)),
        "clipped_highlight_fraction": float(np.mean(luma >= 0.992)),
    }


_SCENE_FEATURE_SCALES = np.asarray(
    [0.24, 0.075, 0.095, 0.075, 0.075, 0.11], dtype=np.float64
)


def _scene_change_score(before: np.ndarray, after: np.ndarray) -> float:
    return float(np.sqrt(np.mean(((after - before) / _SCENE_FEATURE_SCALES) ** 2)))


def detect_scene_boundaries(
    stats: list[dict],
    duration: float,
    *,
    minimum_seconds: float,
    change_threshold: float,
    max_keyframes: int,
    persistence: int = 2,
) -> tuple[list[dict[str, float]], float]:
    """Detect sustained grading-state changes in a dense probe timeline.

    A conventional edit/cut is not sufficient. Both sides must remain different
    across multiple probes, then temporal non-maximum suppression enforces the
    minimum stable-segment duration. The result is a small set of candidate
    *grade* boundaries rather than every camera cut in the movie.
    """
    ordered = sorted(stats, key=lambda item: float(item.get("_timestamp") or 0.0))
    window = max(2, int(persistence))
    if len(ordered) < window * 2 + 1:
        return [], 0.0
    features = np.vstack([_scene_feature(item) for item in ordered])
    candidates: list[dict[str, float]] = []
    for index in range(window, len(ordered) - window + 1):
        before_block = features[index - window:index]
        after_block = features[index:index + window]
        before = np.median(before_block, axis=0)
        after = np.median(after_block, axis=0)
        score = _scene_change_score(before, after)
        if score < float(change_threshold):
            continue
        # Reject a candidate if either side is itself wildly unstable. This is
        # the persistence test that keeps flashes/fades/camera cuts from being
        # mistaken for a new long-lived grading state.
        before_jitter = float(np.median([_scene_change_score(before, row) for row in before_block]))
        after_jitter = float(np.median([_scene_change_score(after, row) for row in after_block]))
        if max(before_jitter, after_jitter) > max(0.80, score * 0.72):
            continue
        left_t = float(ordered[index - 1].get("_timestamp") or 0.0)
        right_t = float(ordered[index].get("_timestamp") or left_t)
        candidates.append({
            "time_seconds": max(0.0, (left_t + right_t) * 0.5),
            "left_seconds": left_t,
            "right_seconds": right_t,
            "score": score,
        })

    configured_keyframe_limit = max(0, int(max_keyframes))
    boundary_limit = None if configured_keyframe_limit == 0 else max(0, configured_keyframe_limit - 1)
    if boundary_limit == 0:
        return [], 0.0
    selected: list[dict[str, float]] = []
    min_gap = max(20.0, float(minimum_seconds))
    for candidate in sorted(candidates, key=lambda item: item["score"], reverse=True):
        timestamp = candidate["time_seconds"]
        if timestamp < min_gap or float(duration) - timestamp < min_gap * 0.65:
            continue
        if any(abs(timestamp - prior["time_seconds"]) <= min_gap * 1.05 for prior in selected):
            continue
        selected.append(candidate)
        if boundary_limit is not None and len(selected) >= boundary_limit:
            break
    selected.sort(key=lambda item: item["time_seconds"])
    if not selected:
        return [], 0.0
    scores = np.asarray([item["score"] for item in selected], dtype=np.float64)
    confidence = clamp(
        float(np.mean(scores)) / max(float(change_threshold) * 1.75, 1e-6)
        * min(1.0, len(ordered) / 18.0)
        * math.exp(-float(np.std(scores)) / max(float(np.mean(scores)), 1e-6) * 0.14),
        0.0,
        1.0,
    )
    return selected, confidence


def refine_scene_boundary(
    stats: list[dict],
    coarse_time: float,
    *,
    search_radius: float,
) -> tuple[float, float]:
    """Locate a coarse boundary more precisely inside a dense local probe set."""
    ordered = sorted(stats, key=lambda item: float(item.get("_timestamp") or 0.0))
    if len(ordered) < 5:
        return float(coarse_time), 0.0
    features = np.vstack([_scene_feature(item) for item in ordered])
    best_time, best_score = float(coarse_time), 0.0
    for index in range(2, len(ordered) - 1):
        left = np.median(features[max(0, index - 2):index], axis=0)
        right = np.median(features[index:min(len(ordered), index + 2)], axis=0)
        score = _scene_change_score(left, right)
        left_t = float(ordered[index - 1].get("_timestamp") or 0.0)
        right_t = float(ordered[index].get("_timestamp") or left_t)
        timestamp = (left_t + right_t) * 0.5
        if abs(timestamp - float(coarse_time)) > float(search_radius) * 1.2:
            continue
        if score > best_score:
            best_time, best_score = timestamp, score
    return max(0.0, best_time), max(0.0, best_score)


def scene_full_sample_timestamps(
    duration: float,
    boundaries: list[float],
    base_target: int,
    per_segment: int = 9,
    max_samples: int = 360,
) -> list[float]:
    """Distribute expensive analysis frames across stable grade segments.

    ``max_samples`` is a real user-owned hard ceiling when positive; 0 means
    unlimited. ``per_segment`` is the desired evidence density, not permission
    to silently exceed a positive ceiling.
    When a movie contains many valid grade segments, the available full-sample
    budget is distributed across them proportionally instead.
    """
    duration = max(0.0, float(duration))
    clean_boundaries = sorted({
        float(value) for value in boundaries
        if 0.5 < float(value) < max(0.5, duration - 0.5)
    })
    edges = [0.0, *clean_boundaries, duration]
    segment_count = max(1, len(edges) - 1)
    desired_per_segment = max(1, int(per_segment))
    configured_cap = int(max_samples)
    desired_target = max(max(1, int(base_target)), segment_count * desired_per_segment)
    target = desired_target if configured_cap == 0 else min(desired_target, max(1, configured_cap))

    lengths = np.asarray([
        max(0.1, edges[i + 1] - edges[i]) for i in range(segment_count)
    ], dtype=np.float64)
    counts = np.zeros(segment_count, dtype=int)

    if target >= segment_count:
        # Give every detected stable grade at least one expensive sample, then
        # raise the common floor toward the requested per-segment density.
        common_floor = min(desired_per_segment, max(1, target // segment_count))
        counts[:] = common_floor
        remaining = max(0, target - int(np.sum(counts)))
    else:
        # A deliberately tiny user ceiling cannot cover every segment. Spend it
        # on the longest segments rather than violating the configured maximum.
        order = np.argsort(-lengths)
        counts[order[:target]] = 1
        remaining = 0

    if remaining:
        weights = lengths / max(float(np.sum(lengths)), 1e-6)
        raw = weights * remaining
        extra = np.floor(raw).astype(int)
        counts += extra
        left = remaining - int(np.sum(extra))
        if left:
            order = np.argsort(-(raw - extra))
            for index in order[:left]:
                counts[int(index)] += 1

    timestamps: list[float] = []
    for index, count in enumerate(counts.tolist()):
        if count <= 0:
            continue
        start, end = edges[index], edges[index + 1]
        length = max(0.01, end - start)
        margin = min(3.0, max(0.35, length * 0.06))
        lo = min(end, start + margin)
        hi = max(lo, end - margin)
        if count == 1 or hi <= lo + 0.001:
            values = [(start + end) * 0.5]
        else:
            values = np.linspace(lo, hi, count).tolist()
        timestamps.extend(float(value) for value in values)
    return sorted({round(max(0.0, min(duration, value)), 6) for value in timestamps})

def build_sample_command(
    path: Path,
    ffmpeg: str,
    timestamp: float,
    width: int,
    height: int,
    mode: str = "cpu",
    gpu_device: int = 0,
) -> list[str]:
    """Build one fast-seek raw-frame command for CPU or CUDA acquisition."""
    base = [
        ffmpeg,
        "-hide_banner",
        "-nostdin",
        "-loglevel", "error",
        "-ss", f"{float(timestamp):.6f}",
    ]
    if mode in {"gpu", "gpu-decode"}:
        base += [
            "-hwaccel", "cuda",
            "-hwaccel_device", str(int(gpu_device)),
        ]
        if mode == "gpu":
            base += ["-hwaccel_output_format", "cuda"]
    base += ["-i", str(path), "-an", "-sn", "-dn"]
    if mode == "gpu":
        # Fast path: keep resize on CUDA, then download the small sample.
        vf = (
            f"scale_cuda={int(width)}:{int(height)}:format=nv12:interp_algo=bilinear,"
            "hwdownload,format=nv12,format=rgb24"
        )
    else:
        # CPU mode, or the CUDA compatibility path. With ``-hwaccel cuda`` but
        # no forced CUDA output surface FFmpeg still uses NVDEC where supported,
        # downloads the decoded frame, and performs only the small resize on CPU.
        vf = f"scale={int(width)}:{int(height)}:flags=area,format=rgb24"
    base += [
        "-vf", vf,
        "-frames:v", "1",
        "-f", "rawvideo",
        "-pix_fmt", "rgb24",
        "pipe:1",
    ]
    return base


def _run_sample_command(
    command: list[str],
    width: int,
    height: int,
    timeout_seconds: float | None = None,
) -> tuple[np.ndarray | None, str]:
    frame_bytes = int(width) * int(height) * 3
    timeout_value = float(_SAMPLE_TIMEOUT_SECONDS if timeout_seconds is None else timeout_seconds)
    try:
        proc = run_capture(command, timeout=max(5.0, timeout_value))
    except subprocess.TimeoutExpired:
        return None, f"FFmpeg sample timed out after {timeout_value:.0f}s; child process terminated."
    raw = proc.stdout or b""
    if proc.returncode == 0 and len(raw) >= frame_bytes:
        frame = np.frombuffer(raw[:frame_bytes], dtype=np.uint8).reshape(height, width, 3)
        return frame, ""
    err = (proc.stderr or b"").decode("utf-8", errors="replace").strip()
    return None, _compact_process_error(err, 3) if err else "FFmpeg returned no complete frame."


def _sample_frame_gpu_strategy(
    path: Path,
    ffmpeg: str,
    timestamp: float,
    width: int,
    height: int,
    gpu_device: int,
    strategy: str,
) -> tuple[np.ndarray | None, str]:
    command = build_sample_command(path, ffmpeg, timestamp, width, height, strategy, gpu_device)
    return _run_sample_command(command, width, height)


def _sample_frame_with_fallback(
    path: Path,
    ffmpeg: str,
    timestamp: float,
    width: int,
    height: int,
    prefer_gpu: bool,
    gpu_device: int,
    fallback_to_cpu: bool,
) -> tuple[np.ndarray | None, str, str]:
    if prefer_gpu:
        errors: list[str] = []
        for strategy in ("gpu", "gpu-decode"):
            frame, error = _sample_frame_gpu_strategy(
                path, ffmpeg, timestamp, width, height, gpu_device, strategy
            )
            if frame is not None:
                return frame, ("gpu-compat" if strategy == "gpu-decode" else "gpu"), " | ".join(errors)
            errors.append(f"{strategy}: {error}")
        if not fallback_to_cpu:
            return None, "gpu", " | ".join(errors)
        cpu_command = build_sample_command(path, ffmpeg, timestamp, width, height, "cpu", gpu_device)
        cpu_frame, cpu_error = _run_sample_command(cpu_command, width, height)
        if cpu_frame is not None:
            return cpu_frame, "cpu-fallback", " | ".join(errors)
        return None, "cpu-fallback", f"GPU: {' | '.join(errors)} | CPU: {cpu_error}"

    command = build_sample_command(path, ffmpeg, timestamp, width, height, "cpu", gpu_device)
    frame, error = _run_sample_command(command, width, height)
    return frame, "cpu", error

