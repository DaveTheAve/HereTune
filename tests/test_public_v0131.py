def test_per_video_force_on_bypasses_confidence_but_keeps_hard_safety():
    cfg = Config()
    # Make the distinction explicit: Global is OFF for every native output. The
    # per-video switches alone request these lower-confidence suggestions.
    for name in AUTO_NATIVE_CONTROLS:
        setattr(cfg.hsp, f"auto_{name}", False)
    metadata = _low_confidence_native_metadata()
    correction = CorrectionProfile(
        suggested_audio_time_offset=0.12,
        av_sync_confidence=0.20,
        suggested_sync_drift_seconds_per_hour=-0.08,
        sync_drift_confidence=0.20,
    )
    overrides = {name: "on" for name in AUTO_NATIVE_CONTROLS}
    native = native_calibration_metadata(
        {
            "metadata": metadata,
            "layout_override": {},
            "hsp_policy_override": overrides,
        },
        metadata, cfg, correction,
    )
    applied = native["native_calibration_applied"]
    assert applied["vertical_alignment"]
    assert applied["stereo_roll"]
    assert applied["eye_scale_shear"]
    assert applied["stitch"]
    assert applied["crop"]
    assert applied["horizon"]
    assert applied["orientation_180"]
    assert applied["eye_swap"]
    assert applied["lens_fov"]
    assert applied["autofocus"]
    assert applied["audio_sync"]
    assert applied["sync_drift"]

    # Force On bypasses confidence, not fundamental validity. A projection that
    # cannot safely use rectangular Zoom/Pan still refuses crop, and missing
    # stereo measurements cannot conjure a disparity correction.
    unsafe = copy.deepcopy(metadata)
    unsafe["projection"] = "fisheye"
    unsafe["stereo_alignment"]["frames"] = 0
    unsafe["stereo_alignment"]["auto_applicable"] = False
    unsafe_native = native_calibration_metadata(
        {
            "metadata": unsafe,
            "layout_override": {},
            "hsp_policy_override": overrides,
        },
        unsafe, cfg, correction,
    )
    assert unsafe_native["native_calibration_applied"]["crop"] is False
    assert unsafe_native["native_calibration_applied"]["vertical_alignment"] is False

