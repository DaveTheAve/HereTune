    # public v0.13.0; every genuinely new output remains opt-in.
    assert cfg.hsp.auto_stereo_disparity is True
    assert cfg.hsp.auto_crop is True
    assert AUTO_NATIVE_CONTROLS["stereo_disparity"]["default"] is True
