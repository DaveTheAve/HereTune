def test_retired_analysis_application_keys_are_rewritten_out_of_config(tmp_path: Path):
    path = tmp_path / "config.toml"
    path.write_text(
        "[analysis]\n"
        "stereo_alignment_auto_apply = true\n"
        "stitch_auto_apply = true\n"
        "horizon_auto_apply = true\n"
        "audio_sync_auto_apply = true\n"
        "auto_crop = true\n\n"
        "[hsp]\n"
        "auto_horizon = false\n",
        encoding="utf-8",
    )
    save_config_patch(path, {"hsp": {"auto_horizon": True}})
    saved = path.read_text(encoding="utf-8")
    analysis_block = saved.split("[hsp]", 1)[0]
    for retired in (
        "stereo_alignment_auto_apply",
        "stitch_auto_apply",
        "horizon_auto_apply",
        "audio_sync_auto_apply",
        "auto_crop =",
    ):
        assert retired not in analysis_block
    # The replacement HSP policy owns crop and preserves v0.13.0's default.
    assert "auto_crop = true" in saved.split("[hsp]", 1)[1]
    assert "auto_horizon = true" in saved


