def test_native_calibration_preserves_legacy_defaults_and_new_outputs_are_opt_in():
    cfg = Config()
    metadata = _calibration_metadata()
    row = {"metadata": metadata, "layout_override": {}}
    correction = CorrectionProfile()

    diagnostic = native_calibration_metadata(row, metadata, cfg, correction)
    assert diagnostic["stereo_alignment_applied"] is True
    assert diagnostic["auto_crop_applied"] is True
    assert diagnostic["stitch_applied"] is False
    assert diagnostic["horizon_leveling_applied"] is False

    cfg.hsp.auto_stereo_roll = True
    cfg.hsp.auto_eye_scale_shear = True
    cfg.hsp.auto_stitch_vectors = True
    cfg.hsp.auto_crop = True
    cfg.hsp.auto_horizon = True
    cfg.hsp.auto_autofocus = True
    native = native_calibration_metadata(row, metadata, cfg, correction)
    assert native["stereo_alignment_applied"] is True
    assert native["stitch_applied"] is True
    assert native["auto_crop_applied"] is True
    assert native["horizon_leveling_applied"] is True
    assert native["autofocus_applied"] is True

    blob = build(
        "v0131-native",
        "Native calibration",
        120.0,
        correction,
        metadata=native,
        source_filename="Native_Calibration_LR.mp4",
    )
    parsed = inspect(blob)
    assert parsed.alignment_keyframes[0].rotation == pytest.approx((0.35, 0.0, -0.20), abs=1e-5)
    assert parsed.stitch_keyframes[0].shift == pytest.approx((0.010, -0.010, 0.004, -0.004), abs=1e-5)
    assert parsed.stitch_keyframes[0].scale == pytest.approx((1.010, 0.990, 1.006, 0.994), abs=1e-5)
    assert parsed.orientation_keyframes[0].orientation == pytest.approx((0.0, 0.0, 1.4), abs=1e-5)
    assert parsed.format_keyframes[0].zoom == pytest.approx((1.10, 1.08), abs=1e-5)
    assert parsed.autofocus_keyframes[0].min_focus_distance == pytest.approx(16.0)


